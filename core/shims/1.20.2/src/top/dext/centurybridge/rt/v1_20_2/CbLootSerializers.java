package top.dext.centurybridge.rt.v1_20_2;

import com.google.gson.JsonArray;
import com.google.gson.JsonElement;
import com.google.gson.JsonObject;
import com.google.gson.JsonSyntaxException;
import com.mojang.serialization.Codec;
import com.mojang.serialization.DataResult;
import com.mojang.serialization.JsonOps;
import java.util.List;
import top.dext.centurybridge.res.LegacyItems;
import top.dext.centurybridge.res.LegacyLoot;

/**
 * The 1.20.1 loot serializers on 1.20.2's codecs.
 *
 * 1.20.1 read and wrote every loot value (condition, function, entry, number / NBT / score
 * provider, pool, table) through a JsonSerializer; 1.20.2 reads and writes the same JSON
 * through a codec per type. The serializer facades (facade/v1_20_2, generated by
 * core/tools/gen_loot_serializer_facades.py) keep the 1.20.1 serializer classes and their
 * methods, and answer them here:
 *
 * <ul>
 * <li>reading: the JSON is first upgraded by the same rules that upgrade a mod's data files
 * (res/LegacyLoot, 1.20.1 -> 1.20.2: a block state property value must be a string), then
 * decoded by the type's 1.20.2 codec. The fields a 1.20.1 base serializer read itself and
 * handed to the subclass -- a conditional function's conditions, a leaf entry's weight,
 * quality, conditions and functions -- are not decoded again: they are left out of the JSON
 * the codec sees and set on the decoded value afterwards, exactly as the 1.20.1 constructor
 * received them, so a caller passing its own arguments gets an object built from those.</li>
 * <li>writing: the value is encoded by its codec and its fields copied into the caller's JSON
 * object, minus the ones the 1.20.1 base serializer writes itself (the same fields).</li>
 * </ul>
 *
 * Nested values (number providers inside a function, conditions inside a condition) are read
 * and written by the 1.20.2 codecs, not through the JsonDeserializationContext /
 * JsonSerializationContext a caller passes in: in 1.20.1 those contexts were the vanilla loot
 * Gson, whose adapters produced exactly what the codecs produce for the same JSON.
 */
public final class CbLootSerializers {

    /** the boundary this layer bridges, for the shared data-format rules */
    static final String FROM = "1.20.1";
    static final String TO = "1.20.2";

    private CbLootSerializers() {
    }

    // ------------------------------------------------------------------ codec plumbing

    /** decode or throw the exception a 1.20.1 serializer threw on malformed JSON */
    public static <T> T decode(Codec<T> codec, JsonElement json, String what) {
        DataResult<T> r = codec.parse(JsonOps.INSTANCE, json);
        return r.result().orElseThrow(() -> new JsonSyntaxException(
            "Invalid " + what + ": " + r.error().map(e -> e.message()).orElse("unknown error")));
    }

    public static <T> JsonElement encode(Codec<T> codec, T value, String what) {
        DataResult<JsonElement> r = codec.encodeStart(JsonOps.INSTANCE, value);
        return r.result().orElseThrow(() -> new JsonSyntaxException(
            "Cannot serialize " + what + ": " + r.error().map(e -> e.message()).orElse("unknown error")));
    }

    /**
     * Copy the fields the codec writes for {@code value} into {@code json}, except {@code skip}
     * (written by the 1.20.1 base serializer the caller extends).
     */
    public static <T> void writeFields(JsonObject json, Codec<T> codec, T value, String what, String... skip) {
        JsonElement e = encode(codec, value, what);
        if (!e.isJsonObject()) {
            throw new JsonSyntaxException("Cannot serialize " + what + " into an object: " + e);
        }
        outer:
        for (var en : e.getAsJsonObject().entrySet()) {
            for (String s : skip) {
                if (s.equals(en.getKey())) {
                    continue outer;
                }
            }
            json.add(en.getKey(), en.getValue());
        }
    }

    // ------------------------------------------------------------------ 1.20.1 JSON -> 1.20.2 JSON

    public static JsonObject legacyCondition(JsonObject c) {
        return LegacyLoot.condition(c.deepCopy(), FROM, TO, LegacyItems.Losses.NONE);
    }

    /** one function: below 1.20.5 a function upgrades to exactly one */
    public static JsonObject legacyFunction(JsonObject f) {
        JsonArray one = new JsonArray();
        one.add(f);
        JsonArray out = LegacyLoot.functions(one, FROM, TO, LegacyItems.Losses.NONE);
        return out.get(0).getAsJsonObject();
    }

    public static JsonObject legacyEntry(JsonObject e) {
        return LegacyLoot.entry(e, FROM, TO, LegacyItems.Losses.NONE);
    }

    public static JsonObject legacyPool(JsonObject p) {
        return LegacyLoot.pool(p, FROM, TO, LegacyItems.Losses.NONE);
    }

    public static JsonObject legacyTable(JsonObject t) {
        return LegacyLoot.table(t, FROM, TO, LegacyItems.Losses.NONE);
    }

    /** a loot value of any kind, as {@link CbLootGson}'s adapters read it */
    static JsonElement legacy(JsonElement json, java.util.function.UnaryOperator<JsonObject> rule) {
        return json != null && json.isJsonObject() ? rule.apply(json.getAsJsonObject()) : json;
    }

    private static JsonObject without(JsonObject json, String... keys) {
        JsonObject j = json.deepCopy();
        for (String k : keys) {
            j.remove(k);
        }
        return j;
    }

    // ------------------------------------------------------------------ the 1.20.1 readers

    /**
     * A condition: the whole object is its own. The data-format rules key on the "condition"
     * field, which a caller of the serializer need not have left in (the 1.20.1 dispatcher did,
     * a direct caller may not): the condition's own type is supplied for the upgrade.
     */
    public static <T> T read(Codec<T> codec, JsonObject json, String conditionId, String what) {
        JsonObject j = json;
        if (!json.has("condition")) {
            j = json.deepCopy();
            j.addProperty("condition", conditionId);
        }
        return decode(codec, legacyCondition(j), what);
    }

    /** a provider has no 1.20.1 -> 1.20.2 JSON rule of its own: decoded as given */
    public static <T> T readProvider(Codec<T> codec, JsonElement json, String what) {
        return decode(codec, json, what);
    }

    /**
     * ConditionalLootFunction.Serializer subclasses: fromJson(json, ctx, conditions). The
     * function's own fields come from the JSON; its conditions are the ones handed in. The
     * data-format rules key on the "function" field, which the 1.20.1 dispatcher left in and a
     * direct caller need not have: the function's own type is supplied for the upgrade.
     */
    public static <T extends net.minecraft.class_120> T readFunction(Codec<T> codec, JsonObject json,
            net.minecraft.class_5341[] conditions, String functionId, String what) {
        JsonObject j = json;
        if (!json.has("function")) {
            j = json.deepCopy();
            j.addProperty("function", functionId);
        }
        T fn = decode(codec, without(legacyFunction(j), "conditions"), what);
        setConditions(fn, conditions);
        return fn;
    }

    /**
     * LeafEntry.Serializer subclasses: fromJson(json, ctx, weight, quality, conditions,
     * functions). The entry's own fields come from the JSON, the rest is what was handed in.
     */
    public static <T extends net.minecraft.class_85> T readLeaf(Codec<T> codec, JsonObject json, int weight, int quality,
            net.minecraft.class_5341[] conditions, net.minecraft.class_117[] functions, String what) {
        T e = decode(codec, without(legacyEntry(json), "conditions", "functions", "weight", "quality"), what);
        setEntryConditions(e, conditions);
        top.dext.centurybridge.shims.v1_20_2.CbLootLeafFields leaf = (top.dext.centurybridge.shims.v1_20_2.CbLootLeafFields) e;
        leaf.cb$setWeight(weight);
        leaf.cb$setQuality(quality);
        List<net.minecraft.class_117> fl = List.of(functions);
        leaf.cb$setFunctions(fl);
        leaf.cb$setCompiledFunctions(net.minecraft.class_131.method_594(fl));
        return e;
    }

    /** what the 1.20.1 ConditionalLootFunction(conditions) constructor set */
    public static void setConditions(net.minecraft.class_120 fn, net.minecraft.class_5341[] conditions) {
        List<net.minecraft.class_5341> l = List.of(conditions);
        top.dext.centurybridge.shims.v1_20_2.CbLootFunctionFields f = (top.dext.centurybridge.shims.v1_20_2.CbLootFunctionFields) fn;
        f.cb$setPredicates(l);
        f.cb$setCompositePredicates(net.minecraft.class_217.method_924(l));
    }

    /** what the 1.20.1 LootPoolEntry(conditions) constructor set */
    public static void setEntryConditions(net.minecraft.class_79 entry, net.minecraft.class_5341[] conditions) {
        List<net.minecraft.class_5341> l = List.of(conditions);
        top.dext.centurybridge.shims.v1_20_2.CbLootEntryFields f = (top.dext.centurybridge.shims.v1_20_2.CbLootEntryFields) entry;
        f.cb$setConditions(l);
        f.cb$setConditionPredicate(net.minecraft.class_217.method_924(l));
    }

    // ------------------------------------------------------------------ a codec seen as a 1.20.1 serializer

    /**
     * The JsonSerializer a 1.20.1 JsonSerializableType handed out (getJsonSerializer), for a
     * 1.20.2 loot type that only has a codec: the mod's own serializer when the codec is one of
     * CbLootJson's, otherwise the codec read and written as a JSON object.
     */
    @SuppressWarnings({"unchecked", "rawtypes"})
    public static top.dext.centurybridge.facade.v1_20_2.class_5335 serializerOf(Codec codec, String what,
            java.util.function.UnaryOperator<JsonObject> legacy) {
        top.dext.centurybridge.facade.v1_20_2.class_5335 own = CbLootJson.legacySerializer(codec);
        if (own != null) {
            return own;
        }
        return new top.dext.centurybridge.facade.v1_20_2.class_5335() {
            @Override
            public void method_516(JsonObject json, Object value, com.google.gson.JsonSerializationContext context) {
                writeFields(json, (Codec<Object>) codec, value, what);
            }

            @Override
            public Object method_517(JsonObject json, com.google.gson.JsonDeserializationContext context) {
                return decode((Codec<Object>) codec, legacy.apply(json), what);
            }
        };
    }

    /**
     * The serializer of a loot type object, as 1.20.1's JsonSerializableType.getJsonSerializer()
     * answered: a CB SerializerType facade carries it, a 1.20.2 loot type record has its codec.
     */
    @SuppressWarnings("rawtypes")
    public static top.dext.centurybridge.facade.v1_20_2.class_5335 serializerOfType(Object type) {
        if (type instanceof top.dext.centurybridge.facade.v1_20_2.class_5336 t) {
            return t.method_29312();
        }
        if (type instanceof net.minecraft.class_5339 t) {
            return serializerOf(t.comp_1858(), "loot function", CbLootSerializers::legacyFunction);
        }
        if (type instanceof net.minecraft.class_5342 t) {
            return serializerOf(t.comp_1878(), "loot condition", CbLootSerializers::legacyCondition);
        }
        if (type instanceof net.minecraft.class_5338 t) {
            return serializerOf(t.comp_1847(), "loot pool entry", CbLootSerializers::legacyEntry);
        }
        if (type instanceof net.minecraft.class_5657 t) {
            return serializerOf(t.comp_1896(), "number provider", j -> j);
        }
        if (type instanceof net.minecraft.class_5650 t) {
            return serializerOf(t.comp_1891(), "nbt provider", j -> j);
        }
        if (type instanceof net.minecraft.class_5669 t) {
            return serializerOf(t.comp_1904(), "score provider", j -> j);
        }
        throw new IllegalArgumentException("CenturyBridge: " + type + " is not a 1.20.1 JsonSerializableType");
    }
}
