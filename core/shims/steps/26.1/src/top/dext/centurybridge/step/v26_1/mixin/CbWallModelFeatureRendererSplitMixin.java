package top.dext.centurybridge.step.v26_1.mixin;

import net.fabricmc.api.EnvType;
import net.fabricmc.api.Environment;
import net.minecraft.client.renderer.MultiBufferSource;
import net.minecraft.client.renderer.OutlineBufferSource;
import net.minecraft.client.renderer.SubmitNodeCollection;
import net.minecraft.client.renderer.feature.ModelFeatureRenderer;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.Shadow;
import top.dext.centurybridge.step.v26_1.rt.CbVanillaReads;
import top.dext.centurybridge.step.v26_1.rt.CbWallFeatureSplits;
import top.dext.centurybridge.step.v26_1.rt.CbWallLegacySplit;

/**
 * 1.21.11's ModelFeatureRenderer.render(..) (class_11683.method_73001), which 26.1 split into renderSolid(..) and renderTranslucent(..) with
 * the same arguments: given back as both halves in turn; a subclass overriding it is called once per frame from
 * vanilla's first half (mixin/CbWallModelFeatureRendererSplitReadsMixin, rt/CbWallLegacySplit). Generated by
 * core/tools/gen_wall_featuresplit.py.
 */
@Environment(EnvType.CLIENT)
@Mixin(value = ModelFeatureRenderer.class, priority = CbVanillaReads.PRIORITY)
public abstract class CbWallModelFeatureRendererSplitMixin implements CbWallFeatureSplits.ModelFeatureRendererLegacy {

    @Shadow
    public abstract void renderSolid(SubmitNodeCollection collection, MultiBufferSource.BufferSource bufferSource, OutlineBufferSource outline, MultiBufferSource.BufferSource crumbling);

    @Shadow
    public abstract void renderTranslucent(SubmitNodeCollection collection, MultiBufferSource.BufferSource bufferSource, OutlineBufferSource outline, MultiBufferSource.BufferSource crumbling);

    /** 1.21.11 ModelFeatureRenderer.render (class_11683.method_73001) */
    @Override
    public void render(SubmitNodeCollection collection, MultiBufferSource.BufferSource bufferSource, OutlineBufferSource outline, MultiBufferSource.BufferSource crumbling) {
        CbWallLegacySplit.enter(this);
        try {
            renderSolid(collection, bufferSource, outline, crumbling);
            renderTranslucent(collection, bufferSource, outline, crumbling);
        } finally {
            CbWallLegacySplit.exit(this);
        }
    }
}
