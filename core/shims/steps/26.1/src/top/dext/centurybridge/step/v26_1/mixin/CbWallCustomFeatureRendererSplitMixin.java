package top.dext.centurybridge.step.v26_1.mixin;

import net.fabricmc.api.EnvType;
import net.fabricmc.api.Environment;
import net.minecraft.client.renderer.MultiBufferSource;
import net.minecraft.client.renderer.SubmitNodeCollection;
import net.minecraft.client.renderer.feature.CustomFeatureRenderer;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.Shadow;
import top.dext.centurybridge.step.v26_1.rt.CbVanillaReads;
import top.dext.centurybridge.step.v26_1.rt.CbWallFeatureSplits;
import top.dext.centurybridge.step.v26_1.rt.CbWallLegacySplit;

/**
 * 1.21.11's CustomFeatureRenderer.render(..) (class_11682.method_72999), which 26.1 split into renderSolid(..) and renderTranslucent(..) with
 * the same arguments: given back as both halves in turn; a subclass overriding it is called once per frame from
 * vanilla's first half (mixin/CbWallCustomFeatureRendererSplitReadsMixin, rt/CbWallLegacySplit). Generated by
 * core/tools/gen_wall_featuresplit.py.
 */
@Environment(EnvType.CLIENT)
@Mixin(value = CustomFeatureRenderer.class, priority = CbVanillaReads.PRIORITY)
public abstract class CbWallCustomFeatureRendererSplitMixin implements CbWallFeatureSplits.CustomFeatureRendererLegacy {

    @Shadow
    public abstract void renderSolid(SubmitNodeCollection collection, MultiBufferSource.BufferSource bufferSource);

    @Shadow
    public abstract void renderTranslucent(SubmitNodeCollection collection, MultiBufferSource.BufferSource bufferSource);

    /** 1.21.11 CustomFeatureRenderer.render (class_11682.method_72999) */
    @Override
    public void render(SubmitNodeCollection collection, MultiBufferSource.BufferSource bufferSource) {
        CbWallLegacySplit.enter(this);
        try {
            renderSolid(collection, bufferSource);
            renderTranslucent(collection, bufferSource);
        } finally {
            CbWallLegacySplit.exit(this);
        }
    }
}
