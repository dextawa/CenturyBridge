package top.dext.centurybridge.step.v26_1.mixin;

import net.fabricmc.api.EnvType;
import net.fabricmc.api.Environment;
import net.minecraft.client.renderer.SubmitNodeCollection;
import net.minecraft.client.renderer.feature.ParticleFeatureRenderer;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.Shadow;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;
import top.dext.centurybridge.step.v26_1.rt.CbWallLegacySplit;

/**
 * 1.21.11's ParticleFeatureRenderer.render(..) (class_11977.method_74407), which 26.1 split into renderSolid(..) and renderTranslucent(..) with
 * the same arguments: given back as both halves in turn; a subclass overriding it is called once per frame from
 * vanilla's first half (rt/CbWallLegacySplit). Generated by core/tools/gen_wall_featuresplit.py.
 */
@Environment(EnvType.CLIENT)
@Mixin(ParticleFeatureRenderer.class)
public abstract class CbWallParticleFeatureRendererSplitMixin {

    @Shadow
    public abstract void renderSolid(SubmitNodeCollection collection);

    @Shadow
    public abstract void renderTranslucent(SubmitNodeCollection collection);

    /** 1.21.11 ParticleFeatureRenderer.render (class_11977.method_74407) */
    public void render(SubmitNodeCollection collection) {
        CbWallLegacySplit.enter(this);
        try {
            renderSolid(collection);
            renderTranslucent(collection);
        } finally {
            CbWallLegacySplit.exit(this);
        }
    }

    @Inject(method = "renderSolid", at = @At("HEAD"), cancellable = true)
    private void cb$legacySolid(SubmitNodeCollection collection, CallbackInfo ci) {
        if (CbWallLegacySplit.legacy(this, ParticleFeatureRenderer.class, "render", SubmitNodeCollection.class)) {
            ci.cancel();
            render(collection);
        }
    }

    @Inject(method = "renderTranslucent", at = @At("HEAD"), cancellable = true)
    private void cb$legacyTranslucent(SubmitNodeCollection collection, CallbackInfo ci) {
        if (CbWallLegacySplit.legacy(this, ParticleFeatureRenderer.class, "render", SubmitNodeCollection.class)) {
            ci.cancel();
        }
    }
}
