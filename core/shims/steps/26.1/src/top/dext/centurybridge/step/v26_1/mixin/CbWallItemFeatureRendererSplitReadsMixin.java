package top.dext.centurybridge.step.v26_1.mixin;

import net.fabricmc.api.EnvType;
import net.fabricmc.api.Environment;
import net.minecraft.client.renderer.MultiBufferSource;
import net.minecraft.client.renderer.OutlineBufferSource;
import net.minecraft.client.renderer.SubmitNodeCollection;
import net.minecraft.client.renderer.feature.ItemFeatureRenderer;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;
import top.dext.centurybridge.step.v26_1.rt.CbWallFeatureSplits;
import top.dext.centurybridge.step.v26_1.rt.CbWallLegacySplit;

/**
 * A 1.21.11 subclass overriding ItemFeatureRenderer.render(..) (class_11687.method_73010, restored by CbWallItemFeatureRendererSplitMixin): vanilla's renderSolid calls it
 * once per frame in place of both halves and its renderTranslucent does nothing for it; a renderer without such an
 * override runs 26.1's halves untouched. Default priority: injectors into 26.1 methods. Generated by
 * core/tools/gen_wall_featuresplit.py.
 */
@Environment(EnvType.CLIENT)
@Mixin(ItemFeatureRenderer.class)
public abstract class CbWallItemFeatureRendererSplitReadsMixin {

    @Inject(method = "renderSolid", at = @At("HEAD"), cancellable = true)
    private void cb$legacySolid(SubmitNodeCollection collection, MultiBufferSource.BufferSource bufferSource, OutlineBufferSource outline, CallbackInfo ci) {
        if (CbWallLegacySplit.legacy(this, ItemFeatureRenderer.class, "render", SubmitNodeCollection.class, MultiBufferSource.BufferSource.class, OutlineBufferSource.class)) {
            ci.cancel();
            ((CbWallFeatureSplits.ItemFeatureRendererLegacy) (Object) this).render(collection, bufferSource, outline);
        }
    }

    @Inject(method = "renderTranslucent", at = @At("HEAD"), cancellable = true)
    private void cb$legacyTranslucent(SubmitNodeCollection collection, MultiBufferSource.BufferSource bufferSource, OutlineBufferSource outline, CallbackInfo ci) {
        if (CbWallLegacySplit.legacy(this, ItemFeatureRenderer.class, "render", SubmitNodeCollection.class, MultiBufferSource.BufferSource.class, OutlineBufferSource.class)) {
            ci.cancel();
        }
    }
}
