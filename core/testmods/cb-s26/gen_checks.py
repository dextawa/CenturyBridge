#!/usr/bin/env python3
"""Writes src/cb/s26/RegConstChecks.java: one check per fieldGetter of regconst-gen.json -- the 26.1.2 constant,
read as a 26.1.2 mod reads it (GETSTATIC, converted one step), must be the object / key / holder 26.1.2 had under
that registry and id (measured by core/tools/RegistryDump.java on 26.1.2: the dump given).

    python3 core/testmods/cb-s26/gen_checks.py <dump-26.1.2.tsv>     (from the repository root)
"""
import json
import sys

DUMP = sys.argv[1]
FRAG = "core/segments/steps/26.1.2__26.2.json.d/regconst-gen.json"
OUT = "core/testmods/cb-s26/src/cb/s26/RegConstChecks.java"

want = {}
for line in open(DUMP, encoding="utf-8"):
    if line.startswith("["):
        continue
    f = line.rstrip("\n").split("\t")
    if len(f) == 7 and f[2] == "":
        want[(f[0], f[1])] = (f[3], f[4], f[5])
keys = sorted(json.load(open(FRAG, encoding="utf-8"))["fieldGetters"])
lines = ["package cb.s26;", "", "/** GENERATED by core/testmods/cb-s26/gen_checks.py -- regenerate, never hand-edit. */",
         "final class RegConstChecks {", "    private RegConstChecks() {}", ""]
chunks = [keys[i:i + 150] for i in range(0, len(keys), 150)]
lines.append("    static void run() {")
for i in range(len(chunks)):
    lines.append(f"        run{i}();")
lines.append("    }")
for i, chunk in enumerate(chunks):
    lines += ["", f"    private static void run{i}() {{"]
    for k in chunk:
        owner, rest = k.rsplit(".", 1)
        name = rest.split(":")[0]
        kind, reg, rid = want[(owner, name)]
        jowner = owner.replace("/", ".").replace("$", ".")
        lines.append(f'        S26TestMod.check("regconst.{owner.rsplit("/", 1)[1]}.{name}", '
                     f'S26TestMod.describe({jowner}.{name}), "{kind}\\t{reg}\\t{rid}");')
    lines.append("    }")
lines += ["}", ""]
with open(OUT, "w", encoding="utf-8", newline="\n") as o:
    o.write("\n".join(lines))
print(f"-> {OUT}: {len(keys)} checks")
