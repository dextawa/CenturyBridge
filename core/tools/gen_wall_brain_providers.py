"""LivingEntity.brainProvider() at the 1.21.11 -> 26.1 wall: given back on each class that had it (covers).

1.21.11's LivingEntity.brainProvider() answered the provider its makeBrain(dynamic) built the brain with -- an
empty one (Brain.provider(no memories, no sensors)) on LivingEntity, each brained mob its own. 26.1 dropped the
method; each brained mob keeps its provider as a static BRAIN_PROVIDER. For every class of the step's damage
table with a brainProvider() row this writes a mixin giving the method back:
  - on LivingEntity: 1.21.11's empty provider (rt/CbWallBrain.provider, Brain.provider's 1.21.11 shape);
  - on a mob 26.1 gives a BRAIN_PROVIDER field: that provider.
A mod's override overrides the given-back method and its super call reaches the one of the class above it, as
in 1.21.11; the mod's makeBrain(dynamic) building from it goes through the makeBrain hook (CbWallBrain).
Classes 26.1 gives no provider field are listed in the report.

  python gen_wall_brain_providers.py <damage.tsv> <W jar> <wall table> <fragment.json> <src root> <mixin config> <report.tsv>

Regenerating (from the repo root):
  python3 core/tools/gen_wall_brain_providers.py core/segments/damage/1.21.11__26.1.damage.tsv data/jars/client-26.1.jar \\
      data/mappings/inter-to-mojang-1.21.11-26.1.tsv core/segments/steps/1.21.11__26.1.json.d/swall-brainproviders-gen.json \\
      core/shims/steps/26.1/src core/shims/steps/26.1/resources/cb-step-26.1.mixins.json <tmp>/brainproviders-report.tsv
"""
import json
import os
import re
import sys
import zipfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import classfile  # noqa: E402

KEY = "method_28306"
DESC = "()Lnet/minecraft/class_4095$class_5303;"
PKG = "top/dext/centurybridge/step/v26_1/mixin"
PREFIX = "CbWallBrainProvider"


def main():
    dmg, wjar, table, frag, src, config, report = sys.argv[1:8]
    cmap = {}
    for line in open(table, encoding="utf-8"):
        f = line.rstrip("\n").split("\t")
        if len(f) >= 3 and f[0] == "C":
            cmap[f[1]] = f[2]
    owners = set()
    for line in open(dmg, encoding="utf-8"):
        f = line.rstrip("\n").split("\t")
        if len(f) >= 4 and f[2] == KEY and f[3] == DESC:
            owners.add(f[1])
    z = zipfile.ZipFile(wjar)
    covers, mixins, rep = [], [], []
    old = [n for n in os.listdir(os.path.join(src, PKG)) if n.startswith(PREFIX) and n.endswith(".java")]
    for n in old:
        os.remove(os.path.join(src, PKG, n))
    for owner in sorted(owners):
        wname = cmap.get(owner, owner)
        entry = wname + ".class"
        if entry not in z.namelist():
            rep.append((owner, "26.1 has no such class"))
            continue
        c = classfile.read(z.read(entry))
        simple = wname.rsplit("/", 1)[1]
        dotted = wname.replace("/", ".")
        if wname == "net/minecraft/world/entity/LivingEntity":
            body = ("    /** 1.21.11's LivingEntity.brainProvider(): no memories, no sensors */\n"
                    "    protected Brain.Provider<?> brainProvider() {\n"
                    "        return CbWallBrain.provider(List.of(), List.of());\n"
                    "    }\n")
            imports = ["java.util.List", "net.minecraft.world.entity.LivingEntity", "net.minecraft.world.entity.ai.Brain",
                       "org.spongepowered.asm.mixin.Mixin", "top.dext.centurybridge.step.v26_1.rt.CbWallBrain"]
        else:
            field = [f for f in c.fields if f[0] == "BRAIN_PROVIDER"]
            if not field:
                rep.append((owner, "26.1's " + wname + " has no BRAIN_PROVIDER"))
                continue
            public = field[0][2] & 0x0001
            shadow = ("" if public else "    @Shadow\n    @Final\n    private static Brain.Provider<" + simple + "> BRAIN_PROVIDER;\n\n")
            ref = (simple + ".BRAIN_PROVIDER") if public else "BRAIN_PROVIDER"
            body = (shadow + "    /** 1.21.11's " + simple + ".brainProvider(): the provider 26.1 keeps as BRAIN_PROVIDER */\n"
                    "    protected Brain.Provider<" + simple + "> brainProvider() {\n"
                    "        return " + ref + ";\n"
                    "    }\n")
            imports = [dotted, "net.minecraft.world.entity.ai.Brain", "org.spongepowered.asm.mixin.Mixin"]
            if not public:
                imports += ["org.spongepowered.asm.mixin.Final", "org.spongepowered.asm.mixin.Shadow"]
        name = PREFIX + simple + "Mixin"
        lines = ["package " + PKG.replace("/", ".") + ";", ""]
        lines += ["import " + i + ";" for i in sorted(imports)]
        lines += ["", "/** Generated by core/tools/gen_wall_brain_providers.py -- do not edit; regenerate with the command in its header. */",
                  "@Mixin(" + simple + ".class)", "public abstract class " + name + " {", "", body + "}", ""]
        with open(os.path.join(src, PKG, name + ".java"), "w", encoding="utf-8", newline="\n") as fh:
            fh.write("\n".join(lines))
        covers.append(owner + "." + KEY + DESC)
        mixins.append(name)
    with open(frag, "w", encoding="utf-8", newline="\n") as fh:
        json.dump({"covers": covers}, fh, indent=1)
        fh.write("\n")
    # the mixin config's common list: the others as they are, then the generated names
    text = open(config, encoding="utf-8").read()
    cfg = json.loads(text)
    cfg["mixins"] = [m for m in cfg["mixins"] if not m.startswith(PREFIX)] + mixins
    with open(config, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(json.dumps(cfg, indent=2) + "\n")
    with open(report, "w", encoding="utf-8", newline="\n") as fh:
        for r in rep:
            fh.write("\t".join(r) + "\n")
    print("%d mixins, report %s" % (len(mixins), report))


if __name__ == "__main__":
    main()
