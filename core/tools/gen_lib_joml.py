"""JOML 1.10.5 (1.21.3) -> 1.10.8 (1.21.4): the methods JOML's read-only interfaces newly demand of an implementation.

  python3 core/tools/gen_lib_joml.py

JOML 1.10.8 added abstract methods to Vector3fc, Vector4dc, Matrix4fc... (core/segments/damage-lib/1.21.3__1.21.4.tsv,
kind ABSTRACT); a 1.21.3-era mod class implementing one of them lacks them (AbstractMethodError on the first call). Each
interface Xc is the read-only view of JOML's own class X, which implements it and copies any Xc (constructor X(Xc)), and
every method of an Xc is a pure function of the receiver's values (it never writes the receiver): so the answer for a mod's
Xc is X's own method run on a copy of it -- except where the method answers the receiver itself (getTransposedToAddress
writes the values and returns this), which answers the mod's object. Writes:
  core/shims/steps/1.21.4/src/top/dext/centurybridge/step/v1_21_4/rt/CbLibJomlFills.java  (generated; never hand-edit)
  core/segments/steps/1.21.3__1.21.4.json.d/lib-joml-gen.json                           (abstractFills)
Rows a hook already answers (Matrix3x2fc.transform, Vector4ic.dot / distanceSquared: lib.json) are left out.
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
TABLE = os.path.join(ROOT, "segments", "damage-lib", "1.21.3__1.21.4.tsv")
JAVA = os.path.join(ROOT, "shims", "steps", "1.21.4", "src", "top", "dext", "centurybridge", "step", "v1_21_4", "rt", "CbLibJomlFills.java")
FRAG = os.path.join(ROOT, "segments", "steps", "1.21.3__1.21.4.json.d", "lib-joml-gen.json")
OWNER = "top/dext/centurybridge/step/v1_21_4/rt/CbLibJomlFills"
HOOKED = {"org/joml/Matrix3x2fc.transform(Lorg/joml/Vector3fc;Lorg/joml/Vector3f;)Lorg/joml/Vector3f;",
          "org/joml/Vector4ic.distanceSquared(IIII)J", "org/joml/Vector4ic.distanceSquared(Lorg/joml/Vector4ic;)J",
          "org/joml/Vector4ic.dot(Lorg/joml/Vector4ic;)J"}
PRIM = {"I": "int", "J": "long", "F": "float", "D": "double", "Z": "boolean", "V": "void"}


def jtype(d):
    if d in PRIM:
        return PRIM[d]
    return d[1:-1].split("/")[-1]


def main():
    rows = []
    for line in open(TABLE, encoding="utf-8"):
        f = line.rstrip("\n").split("\t")
        if len(f) > 3 and f[0] == "org/joml/joml" and f[2] == "ABSTRACT" and f[3] not in HOOKED:
            rows.append(f[3])
    methods, fills = [], []
    for sym in sorted(rows):
        iface, md = sym.split(".", 1)
        name, desc = md[:md.index("(")], md[md.index("("):]
        args = re.findall(r"\[*(?:L[^;]+;|[ZBCSIJFD])", desc[1:desc.index(")")])
        ret = desc[desc.index(")") + 1:]
        simple = iface.split("/")[-1]
        concrete = simple[:-1]
        params = ", ".join(f"{jtype(a)} a{i}" for i, a in enumerate(args))
        call = ", ".join(f"a{i}" for i in range(len(args)))
        sig = f"    public static {jtype(ret)} {name}({simple} self{', ' if params else ''}{params})"
        if ret == f"L{iface};":
            body = f"        new {concrete}(self).{name}({call});\n        return self;"
        else:
            body = f"        return new {concrete}(self).{name}({call});"
        methods.append(f"    /** {simple}.{name}{desc} */\n{sig} {{\n{body}\n    }}\n")
        fills.append({"under": iface, "method": md,
                      "call": f"{OWNER}.{name}(L{iface};{''.join(args)}){ret}",
                      "basis": f"JOML 1.10.8 demands {simple}.{name}; a 1.10.5 implementation answers through JOML's own {concrete} "
                               f"copy of it (rt/CbLibJomlFills)"})
    imports = sorted({t.split("/")[-1] for s in rows for t in re.findall(r"L(org/joml/[^;]+);", s.split(".", 1)[1])} |
                     {s.split(".")[0].split("/")[-1] for s in rows} | {s.split(".")[0].split("/")[-1][:-1] for s in rows})
    src = ["package top.dext.centurybridge.step.v1_21_4.rt;", ""]
    src += [f"import org.joml.{c};" for c in imports]
    src += ["", "/**",
            " * Generated by core/tools/gen_lib_joml.py -- regenerate, never hand-edit. The methods JOML 1.10.8's read-only interfaces",
            " * newly demand, for a 1.10.5-era mod implementation: JOML's own class run on a copy of the mod's object (every method of",
            " * an Xc is a pure function of the receiver), the receiver itself where JOML answers it.",
            " */",
            "public final class CbLibJomlFills {",
            "    private CbLibJomlFills() {",
            "    }", ""]
    src += methods
    src += ["}", ""]
    with open(JAVA, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(src))
    with open(FRAG, "w", encoding="utf-8", newline="\n") as f:
        json.dump({"_lib_joml_basis": "generated by core/tools/gen_lib_joml.py -- regenerate, never hand-edit", "abstractFills": fills}, f, indent=1)
        f.write("\n")
    print(f"{len(fills)} fills -> {FRAG}, {JAVA}")


if __name__ == "__main__":
    main()
