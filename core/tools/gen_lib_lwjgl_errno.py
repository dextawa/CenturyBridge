"""LWJGL 3.3.3 (1.21.11) -> 3.4.1 (26.1): the Windows / Linux bindings that take the error out-parameter.

  python3 core/tools/gen_lib_lwjgl_errno.py <W libraries dir>

LWJGL 3.3.3's Win32 and Linux functions saved GetLastError() / errno after the call in a per-thread slot, read back with
WinBase.getLastError() / LibCErrno.getErrno(). 3.4.1 drops both getters and gives every such function a leading
`IntBuffer _GetLastError` / `IntBuffer _errno` (its n-variant: the buffer's address, `long`), filled after the call when
not null. So a 3.3.3 call is the 3.4.1 one with a per-thread one-int buffer (rt/CbLibLwjglErrors) as that argument, and
the 3.3.3 getters read that buffer -- the value the last such call saved on this thread, as 3.3.3 answered.
For every METHOD row of core/segments/damage-lib/1.21.11__26.1.tsv whose class 3.4.1 still has a same-name method taking
exactly one more leading IntBuffer (or long, for n-variants), a callReshapes entry pushes the buffer (or its address).
Writes core/segments/steps/1.21.11__26.1.json.d/lib-lwjgl-errno-gen.json. Regenerate, never hand-edit.
"""
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
R = "top/dext/centurybridge/step/v26_1/rt/CbLibLwjglErrors"


def main():
    libdir = sys.argv[1]
    table = os.path.join(ROOT, "segments", "damage-lib", "1.21.11__26.1.tsv")
    rows = {}
    for line in open(table, encoding="utf-8"):
        f = line.rstrip("\n").split("\t")
        if len(f) > 3 and f[2] == "METHOD" and "lwjgl" in f[0]:
            owner, member = f[3].split(".", 1)
            rows.setdefault(owner, []).append(member)
    jars = [os.path.join(r, n) for r, _, fs in os.walk(libdir) for n in fs
            if n.endswith(".jar") and "lwjgl" in r and "natives" not in n]
    cp = os.pathsep.join(jars)
    reshapes = {}
    for owner, members in sorted(rows.items()):
        out = subprocess.run(["javap", "-s", "-cp", cp, owner.replace("/", ".")], capture_output=True, text=True).stdout
        w = {}
        name = None
        for ln in out.splitlines():
            m = re.match(r"\s+public static .* (\w+)\(.*\);$", ln)
            if m:
                name = m.group(1)
                continue
            d = re.match(r"\s+descriptor: (\(.*)$", ln)
            if d and name:
                w.setdefault(name, set()).add(d.group(1))
                name = None
        windows = "/windows/" in owner or owner == "org/lwjgl/opengl/WGL"
        kind = "lastError" if windows else "errno"
        for member in members:
            mname, desc = member[:member.index("(")], member[member.index("("):]
            nargs = len(re.findall(r"\[*(?:L[^;]+;|[ZBCSIJFD])", desc[1:desc.index(")")]))
            buf, addr = "(Ljava/nio/IntBuffer;" + desc[1:], "(J" + desc[1:]
            if buf in w.get(mname, ()):
                push = f"push {R}#{kind}Buffer()Ljava/nio/IntBuffer;"
                new = buf
            elif mname.startswith("n") and addr in w.get(mname, ()):
                push = f"push {R}#{kind}Address()J"
                new = addr
            else:
                continue
            reshapes[f"{owner}.{member}"] = {"desc": new, "ops": [push] + ["keep"] * nargs,
                                             "basis": f"LWJGL 3.4.1 takes the {'GetLastError' if windows else 'errno'} out-parameter 3.3.3 "
                                                      f"saved per thread; the per-thread buffer of rt/CbLibLwjglErrors, read back by "
                                                      f"{'WinBase.getLastError()' if windows else 'LibCErrno.getErrno()'}"}
    frag = {"_lib_lwjgl_errno_basis": "generated by core/tools/gen_lib_lwjgl_errno.py -- regenerate, never hand-edit",
            "callReshapes": dict(sorted(reshapes.items())),
            "staticRedirects": {"org/lwjgl/system/windows/WinBase.getLastError()I": R,
                                "org/lwjgl/system/libc/LibCErrno.getErrno()I": R}}
    with open(os.path.join(ROOT, "segments", "steps", "1.21.11__26.1.json.d", "lib-lwjgl-errno-gen.json"), "w",
              encoding="utf-8", newline="\n") as f:
        json.dump(frag, f, indent=1)
        f.write("\n")
    print(f"{len(reshapes)} calls take the per-thread error buffer")


if __name__ == "__main__":
    main()
