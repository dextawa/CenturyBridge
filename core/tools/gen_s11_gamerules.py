"""gen_s11_gamerules.py: the 1.21.10 vanilla game rules on 1.21.11 (step 1.21.10 -> 1.21.11).

1.21.10 GameRules.RULE_* were Key<BooleanValue|IntegerValue> named by camelCase ids; 1.21.11 keeps fields of the
same intermediary names typed GameRule<Boolean|Integer>, registered under new ids. The pairing is read from
bytecode only: each 1.21.10 field's id, category and value type from GameRules.<clinit> (the register call
following the id constant), each 1.21.11 field's value type from its signature; the conversion of the three
inverted rules and the fire-tick pair is 1.21.11's own GameRuleRegistryFix (class_12255), checked here
against its bytecode (the inverting operator is applied to exactly those three ids, and doFireTick +
allowFireTicksAwayFromPlayer are merged into fire_spread_radius_around_player).

  python3 core/tools/gen_s11_gamerules.py <V code jar> <W code jar>
writes core/shims/steps/1.21.11/src/top/dext/centurybridge/step/v1_21_11/rt/CbGameRulesVanilla.java and
core/segments/steps/1.21.10__1.21.11.json.d/s11-gamerules-gen.json (fieldGetters for every RULE_* field).
"""
import json
import re
import subprocess
import sys

VJAR, WJAR = sys.argv[1], sys.argv[2]
PKG = "top/dext/centurybridge/step/v1_21_11"
OUT_JAVA = f"core/shims/steps/1.21.11/src/{PKG}/rt/CbGameRulesVanilla.java"
OUT_JSON = "core/segments/steps/1.21.10__1.21.11.json.d/s11-gamerules-gen.json"
CATS = {"field_24094": "PLAYER", "field_24095": "MOBS", "field_24096": "SPAWNING", "field_24097": "DROPS",
        "field_24098": "UPDATES", "field_24099": "CHAT", "field_24100": "MISC"}
BOOL_CREATE = {"method_20759", "method_20760", "method_70743"}
INT_CREATE = {"method_20768", "method_20766", "method_56115"}


def javap(jar, cls, code=True):
    args = ["javap", "-p"] + (["-c"] if code else ["-s"]) + ["-cp", jar, cls]
    return subprocess.run(args, capture_output=True, text=True, check=True).stdout


def v_rules():
    txt = javap(VJAR, "net.minecraft.class_1928").split("static {};")[1]
    out, sid, cat, typ = [], None, None, None
    for line in txt.splitlines():
        m = re.search(r"// String (\S+)", line)
        if m:
            sid, cat, typ = m.group(1), None, None
        m = re.search(r"class_1928\$class_5198\.(field_\d+)", line)
        if m and sid:
            cat = CATS[m.group(1)]
        m = re.search(r"class_1928\$class_43(10|12)\.(method_\d+)", line)
        if m and sid and typ is None:
            typ = "bool" if m.group(2) in BOOL_CREATE else "int" if m.group(2) in INT_CREATE else None
        m = re.search(r"putstatic .*Field (field_\d+):Lnet/minecraft/class_1928\$class_4313;", line)
        if m:
            assert sid and cat and typ, (m.group(1), sid, cat, typ)
            out.append((m.group(1), sid, cat, typ))
            sid = None
    return out


def w_types():
    txt = javap(WJAR, "net.minecraft.class_1928", code=False)
    t = {}
    for m in re.finditer(r"public static final net\.minecraft\.class_12279<java\.lang\.(Boolean|Integer)> (field_\d+);", txt):
        t[m.group(2)] = "bool" if m.group(1) == "Boolean" else "int"
    return t


def fix_checks():
    txt = javap(WJAR, "net.minecraft.class_12255")
    # the renames that apply the inverting operator (InvokeDynamic #5 = method_76069, !parseBoolean)
    inverted = set(re.findall(r'String (\w+)\n\s+\d+: ldc(?:_w)?\s+#\d+\s+// String minecraft:\w+\n\s+\d+: invokedynamic #216', txt))
    assert "allowFireTicksAwayFromPlayer" in txt and "minecraft:fire_spread_radius_around_player" in txt
    return inverted


def main():
    vr, wt = v_rules(), w_types()
    inverted = fix_checks()
    assert inverted == {"disableRaids", "disablePlayerMovementCheck", "disableElytraMovementCheck"}, inverted
    rows = []
    for f, sid, cat, typ in vr:
        if sid == "doFireTick":
            kind, wf = "FIRE_TICK", "field_56559"
        elif sid == "allowFireTicksAwayFromPlayer":
            kind, wf = "FIRE_AWAY", "field_56559"
        else:
            wf = f
            assert wt.get(wf) == typ, (f, sid, typ, wt.get(wf))
            kind = "INVERT" if sid in inverted else ("BOOL" if typ == "bool" else "INT")
        rows.append((f, sid, cat, typ, kind, wf))
    lines = [
        "package top.dext.centurybridge.step.v1_21_11.rt;",
        "",
        "import top.dext.centurybridge.step.v1_21_11.facade.GameRules;",
        "",
        "/**",
        " * Generated by core/tools/gen_s11_gamerules.py -- do not edit. 1.21.10's vanilla GameRules.RULE_* keys on 1.21.11:",
        " * id, category and value type as 1.21.10's GameRules.&lt;clinit&gt; registered them, the 1.21.11 rule field they read,",
        " * and how the value converts (GameRuleRegistryFix: BOOL/INT as is, INVERT negated, FIRE_* the fire spread radius).",
        " */",
        "public final class CbGameRulesVanilla {",
        "    private CbGameRulesVanilla() {",
        "    }",
        "",
        "    static void register() {",
    ]
    inv = {v: k for k, v in CATS.items()}
    for f, sid, cat, typ, kind, wf in rows:
        catf = inv[cat]
        lines.append(f'        CbGameRules.vanilla("{sid}", GameRules.Category.{catf}, CbGameRules.Kind.{kind}, net.minecraft.class_1928.{wf});')
    lines.append("    }")
    lines.append("")
    for f, sid, cat, typ, kind, wf in rows:
        vt = "BooleanValue" if typ == "bool" else "IntegerValue"
        lines.append(f"    /** 1.21.10 GameRules.{f} ({sid}) */")
        lines.append(f"    @SuppressWarnings(\"unchecked\")")
        lines.append(f"    public static GameRules.Key<GameRules.{vt}> {f}() {{")
        lines.append(f'        return (GameRules.Key<GameRules.{vt}>) CbGameRules.vanillaKey("{sid}");')
        lines.append("    }")
        lines.append("")
    lines[-1:] = ["}", ""]
    open(OUT_JAVA, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
    fg = {f"net/minecraft/class_1928.{f}:Lnet/minecraft/class_1928$class_4313;": f"{PKG}/rt/CbGameRulesVanilla"
          for f, *_ in rows}
    doc = {"_s11_gamerules_gen_basis": "gen_s11_gamerules.py: 1.21.10 GameRules.RULE_* keys read as the layer's Key facades "
                     "(rt/CbGameRulesVanilla, ids and conversions from 1.21.10 GameRules.<clinit> and 1.21.11 GameRuleRegistryFix)",
           "fieldGetters": dict(sorted(fg.items()))}
    open(OUT_JSON, "w", encoding="utf-8", newline="\n").write(json.dumps(doc, indent=1) + "\n")
    print(len(rows), "rules;", sum(1 for r in rows if r[4] not in ("BOOL", "INT")), "converted")


main()
