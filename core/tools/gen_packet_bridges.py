"""The 1.20.4 packet surface on 1.20.5's stream codecs (area s4net of step 1.20.4 -> 1.20.5).

1.20.5 builds every packet from a StreamCodec. The read constructor P(FriendlyByteBuf) became
private, or takes a RegistryFriendlyByteBuf, or is gone where a record's codec reads its components;
write(FriendlyByteBuf) left the Packet interface, and each packet's own writer is private, under
another name, reached only through the class's STREAM_CODEC. For every damage row of that kind
(core/segments/damage/1.20.4__1.20.5.damage.tsv: P.<init>(FriendlyByteBuf), P.write(FriendlyByteBuf),
the unit packets' no-argument constructors, the movement packets' static readers) this decides, from
both releases' bytecode, how 1.20.4's member comes back:

  write(buf)      a mixin restores public write(FriendlyByteBuf) on P (covers): the packet is encoded
                  with P's own STREAM_CODEC, as 1.20.5 writes it (through a RegistryFriendlyByteBuf view
                  where the codec wants one); a write that wrote nothing in 1.20.4 (bundle and unit
                  packets) writes nothing. The packet then implements CbNetLegacyPacket, which a call of
                  Packet.write(buf) through the interface dispatches to. A writer 1.20.5 kept under the
                  same name, only private, is opened by the layer's access widener instead.
  new P(buf)      private P(FriendlyByteBuf): the access widener opens it. P(RegistryFriendlyByteBuf):
                  opened and reshaped, the buffer passed as a RegistryFriendlyByteBuf view. No read
                  constructor: a factory decodes with P's STREAM_CODEC (ctorRedirects).
  super(buf)      as new, where a read constructor is there; otherwise the constructor that takes P's
                  fields in order, each argument the field of one packet decoded from the buffer (records:
                  the canonical constructor and the component accessors); where 1.20.4's read constructor
                  never read the buffer, the no-argument constructor with the buffer dropped.
  new P()         a unit packet (1.20.5 keeps one instance and its codec encodes only that one): the
                  factory answers the instance; a subclass's super() gets the private constructor opened.
  P.read(buf)     a static reader 1.20.5 made private: opened.

Anything else in those rows is reported as "design" and left to the hand-written wiring. Members the
hand-written wiring (the step's other fragments) handles already are skipped.

Outputs (regenerate, never hand-edit):
  <layer>/src/.../mixin/CbNetWrite<Name>.java      one per packet whose write comes back by mixin
  <layer>/src/.../rt/CbNetPacketReaders.java       the factories and the spread helpers
  <wiring>.d/s4net-packets.json                    covers, ctorRedirects, superCtorReshapes
  <layer>/resources/cb-step-1.20.5.accesswidener    the block between the s4net-packets markers
  <layer>/resources/cb-step-1.20.5.mixins.json      the CbNetWrite* entries of "mixins" (others kept)

  python gen_packet_bridges.py <damage.tsv> <V code jar> <W code jar> <layer dir> <step wiring.json> <class names.tsv> <report.tsv>
"""
import json
import os
import re
import sys
import zipfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import classfile  # noqa: E402
from classfile import ACC_ABSTRACT, ACC_FINAL, ACC_PRIVATE, ACC_PROTECTED, ACC_PUBLIC, ACC_STATIC  # noqa: E402

AREA = re.compile(r"^net/minecraft/(network/|server/network/|client/multiplayer/)")
BUF = "Lnet/minecraft/class_2540;"            # FriendlyByteBuf
REG_BUF = "Lnet/minecraft/class_9129;"        # RegistryFriendlyByteBuf
BYTEBUF = "Lio/netty/buffer/ByteBuf;"
CODEC = "Lnet/minecraft/class_9139;"          # StreamCodec
WRITE = "method_11052"                        # 1.20.4 Packet.write(FriendlyByteBuf)
PKG = "top/dext/centurybridge/step/v1_20_5"
READERS = PKG + "/rt/CbNetPacketReaders"
BUFS = PKG + "/rt/CbNetBufs"
LEGACY = PKG + "/rt/CbNetLegacyPacket"
AW_BEGIN = "# --- s4net packets: generated by core/tools/gen_packet_bridges.py, do not edit by hand ---"
AW_END = "# --- end s4net packets ---"
# hand-written elsewhere: the Packet interface, the custom-payload packets (their payloads), and
# whatever another wiring fragment of the step names
SKIP = {"net/minecraft/class_2596", "net/minecraft/class_2658", "net/minecraft/class_2817"}


def load(jar, names):
    out = {}
    with zipfile.ZipFile(jar) as z:
        have = set(z.namelist())
        for n in names:
            if n + ".class" in have:
                out[n] = classfile.read(z.read(n + ".class"), True)
    return out


def method(c, name, desc):
    for m in c.methods:
        if m.name == name and m.desc == desc:
            return m
    return None


def instance_fields(c):
    return [f for f in c.fields if not f[2] & ACC_STATIC]


def codec_fields(c):
    """public static final StreamCodec<B, c> fields: (name, buffer descriptor)"""
    out = []
    for f in c.fields:
        name, desc, acc = f[0], f[1], f[2]
        sig = f[3] if len(f) > 3 else None
        if desc != CODEC or not (acc & ACC_STATIC) or not (acc & ACC_PUBLIC) or not sig:
            continue
        m = re.match(r"Lnet/minecraft/class_9139<(L[^<;]+;)L" + re.escape(c.name) + r";>;$", sig)
        if m:
            out.append((name, m.group(1)))
    return out


# the JDK supertypes a field's type may be handed to a constructor as (a List field built from a Collection)
JDK_SUPERS = {
    "Ljava/util/List;": {"Ljava/util/Collection;", "Ljava/lang/Iterable;"},
    "Ljava/util/Set;": {"Ljava/util/Collection;", "Ljava/lang/Iterable;"},
}


def field_constructor(c, fields):
    """the constructor of c taking its instance fields in order: each parameter the field's type or a
    JDK supertype of it (the constructor then stores what it is handed, or a copy of it); one taking
    the exact types wins"""
    exact = [f[1] for f in fields]
    loose = None
    for m in c.methods:
        if m.name != "<init>":
            continue
        params = classfile.split_args(m.desc)[0]
        if params == exact:
            return m
        if len(params) == len(fields) and all(p == f or p in JDK_SUPERS.get(f, ()) for p, f in zip(params, exact)):
            loose = loose or m
    return loose


def bare_return(m):
    return m is not None and m.code is not None and m.code == b"\xb1"


def reads_param(m):
    """whether a constructor or method body reads its first parameter (slot 1)"""
    return 1 in classfile.slots_read(m.code)


def getter_of(c, field):
    """a public no-argument method of c answering the instance field as it is: aload_0, getfield, return"""
    name, desc = field[0], field[1]
    for m in c.methods:
        if m.desc != "()" + desc or not (m.access & ACC_PUBLIC) or m.access & ACC_STATIC or m.code is None:
            continue
        # aload_0 (2a) getfield #idx (b4 hi lo) xreturn
        if len(m.code) == 5 and m.code[0] == 0x2A and m.code[1] == 0xB4 and 0xAC <= m.code[4] <= 0xB0:
            if m.name == name:  # a record component's accessor carries the field's name
                return m.name
    for m in c.methods:  # a class's getter: matched by the field it reads, from the constant pool
        if m.desc == "()" + desc and m.access & ACC_PUBLIC and not m.access & ACC_STATIC and m.code is not None \
                and len(m.code) == 5 and m.code[0] == 0x2A and m.code[1] == 0xB4:
            if getattr(c, "_field_refs", {}).get((m.code[2] << 8) | m.code[3]) == name:
                return m.name
    return None


def field_refs(raw):
    """constant-pool index of every Fieldref of this class's own fields -> field name"""
    import struct
    n = struct.unpack(">H", raw[8:10])[0]
    i, idx = 10, 1
    utf8, cls, nat, fref = {}, {}, {}, {}
    while idx < n:
        tag = raw[i]
        if tag == 1:
            ln = struct.unpack(">H", raw[i + 1:i + 3])[0]
            utf8[idx] = raw[i + 3:i + 3 + ln].decode("utf-8", "replace")
            i += 3 + ln
        elif tag in (3, 4):
            i += 5
        elif tag in (5, 6):
            i += 9
            idx += 1
        elif tag == 7:
            cls[idx] = struct.unpack(">H", raw[i + 1:i + 3])[0]
            i += 3
        elif tag in (8, 16, 19, 20):
            i += 3
        elif tag == 9:
            fref[idx] = struct.unpack(">HH", raw[i + 1:i + 5])
            i += 5
        elif tag == 12:
            nat[idx] = struct.unpack(">HH", raw[i + 1:i + 5])
            i += 5
        elif tag in (10, 11, 17, 18):
            i += 5
        elif tag == 15:
            i += 4
        else:
            return {}
        idx += 1
    out = {}
    for k, (ci, ni) in fref.items():
        out[k] = utf8.get(nat.get(ni, (0, 0))[0])
    return out


class Names:
    def __init__(self, path):
        self.cm = {}
        for line in open(path, encoding="utf-8"):
            f = line.rstrip("\n").split("\t")
            if len(f) >= 3 and f[0] == "C":
                self.cm[f[1]] = f[2]

    def mojang(self, c):
        if c in self.cm:
            return self.cm[c]
        d = c.rfind("$")
        return self.mojang(c[:d]) + c[d:] if d > 0 else c

    def simple(self, c):
        """a Java identifier for the class: its Mojang simple name, nesting flattened"""
        m = self.mojang(c)
        return m[m.rfind("/") + 1:].replace("$", "")


def jtype(desc):
    """a field/parameter descriptor as Java source (intermediary nested classes as Outer.Inner)"""
    dims = 0
    while desc.startswith("["):
        dims += 1
        desc = desc[1:]
    prim = {"Z": "boolean", "B": "byte", "C": "char", "S": "short", "I": "int", "J": "long", "F": "float", "D": "double", "V": "void"}
    t = prim.get(desc) or desc[1:-1].replace("/", ".").replace("$", ".")
    return t + "[]" * dims


def wired_keys(wiring):
    """every member key the step's hand-written fragments (not ours) wire, by section"""
    keys = set()
    d = wiring + ".d"
    for f in sorted(os.listdir(d)) if os.path.isdir(d) else []:
        if not f.endswith(".json") or f in ("mechanical.json", "s4net-packets.json"):
            continue
        j = json.load(open(os.path.join(d, f), encoding="utf-8"))
        for sec, v in j.items():
            if isinstance(v, dict):
                keys.update(v.keys())
            elif sec == "covers":
                keys.update(v)
    return keys


def main():
    damage, vjar, wjar, layer, wiring, names_tsv, report = sys.argv[1:8]
    names = Names(names_tsv)
    rows = []
    for i, line in enumerate(open(damage, encoding="utf-8")):
        if i == 0:
            continue
        r = line.rstrip("\n").split("\t")
        if AREA.search(names.mojang(r[1])) and r[1] not in SKIP:
            rows.append(r)
    owners = sorted({r[1] for r in rows})
    V, W = load(vjar, owners), load(wjar, owners)
    with zipfile.ZipFile(wjar) as z:
        for n, c in W.items():
            c._field_refs = field_refs(z.read(n + ".class"))
    taken = wired_keys(wiring)

    covers, ctor_redirects, reshapes, aw = [], {}, {}, []
    mixins, readers, fates = {}, [], []

    def fate(r, what, detail=""):
        fates.append((r[0], r[1], r[2], r[3], what, detail))

    def aw_method(owner, name, desc, why):
        line = f"accessible method {owner} {name} {desc}"
        if line not in [a[0] for a in aw]:
            aw.append((line, why))

    def reader_codec(w):
        cs = codec_fields(w)
        return cs[0] if len(cs) == 1 else None

    def decode_expr(w, var):
        cf = reader_codec(w)
        if cf is None:
            return None
        arg = f"{jtype('L' + BUFS + ';').rsplit('.', 1)[-1]}.cbRegistryBuf({var})" if cf[1] == REG_BUF else var
        return f"{jtype('L' + w.name + ';')}.{cf[0]}.decode({arg})"

    def factory(w, simple):
        """cbRead<Name>(FriendlyByteBuf): P decoded with its STREAM_CODEC"""
        name = f"cbRead{simple}"
        if name not in [x[0] for x in readers]:
            expr = decode_expr(w, "buf")
            readers.append((name, f"    /** new {simple}(FriendlyByteBuf): decoded with its STREAM_CODEC, as 1.20.5 reads it */\n"
                                  f"    public static {jtype('L' + w.name + ';')} {name}(class_2540 buf) {{\n"
                                  f"        return {expr};\n    }}\n"))
        return name

    for r in rows:
        usage, owner, name, desc = r[0], r[1], r[2], r[3]
        key = f"{owner}.{name}{desc}"
        v, w = V.get(owner), W.get(owner)
        if key in taken:
            fate(r, "wired", "hand-written fragment")
            continue
        if v is None or w is None:
            fate(r, "design", "class gone or new")
            continue
        simple = names.simple(owner)

        if name == WRITE and desc == "(" + BUF + ")V" and usage in ("call", "override+super"):
            vm = method(v, WRITE, desc)
            if vm is None or vm.access & ACC_ABSTRACT:
                fate(r, "design", "1.20.4 class does not declare write itself")
                continue
            wm = method(w, WRITE, desc)
            if wm is not None:
                if wm.access & ACC_PRIVATE and not wm.access & ACC_STATIC:
                    aw_method(owner, WRITE, desc, f"{simple}: 1.20.5 keeps write under its name, private")
                    fate(r, "aw", "write kept, private")
                else:
                    fate(r, "design", "write kept with another access")
                continue
            if bare_return(vm):
                body = None
            else:
                cf = reader_codec(w)
                if cf is None or w.access & ACC_ABSTRACT:
                    fate(r, "design", "no single STREAM_CODEC to write with")
                    continue
                body = cf
            mixins[owner] = (simple, body, vm.access)
            ck = f"{owner}.{WRITE}{desc}"
            if ck not in covers:
                covers.append(ck)
            fate(r, "mixin", "writes nothing, as 1.20.4" if body is None else f"encodes with {body[0]} ({'registry view' if body[1] == REG_BUF else 'buffer'})")
            continue

        if name == "<init>" and desc == "(" + BUF + ")V" and usage in ("new", "super-ctor"):
            wc = method(w, "<init>", desc)
            wr = method(w, "<init>", "(" + REG_BUF + ")V")
            if wc is not None:
                if not wc.access & ACC_PUBLIC:
                    aw_method(owner, "<init>", desc, f"{simple}: the read constructor, private in 1.20.5")
                fate(r, "aw", "read constructor kept, private")
                continue
            if wr is not None:
                if not wr.access & ACC_PUBLIC:
                    aw_method(owner, "<init>", "(" + REG_BUF + ")V", f"{simple}: the read constructor, private and on a RegistryFriendlyByteBuf in 1.20.5")
                reshapes[key] = {"desc": "(" + REG_BUF + ")V",
                                 "ops": [f"conv {BUFS}#cbRegistryBuf({BUF}){REG_BUF}"],
                                 "basis": "s4net packets: the read constructor takes a RegistryFriendlyByteBuf in 1.20.5"}
                fate(r, "reshape", "registry view")
                continue
            if usage == "new":
                if decode_expr(w, "buf") is None:
                    fate(r, "design", "no read constructor and no single STREAM_CODEC")
                    continue
                ctor_redirects[key] = f"{READERS}#{factory(w, simple)}"
                fate(r, "factory", "decoded with STREAM_CODEC")
                continue
            # super(buf) in a subclass, no read constructor to call
            vc = method(v, "<init>", desc)
            noarg = method(w, "<init>", "()V")
            if vc is not None and not reads_param(vc) and noarg is not None:
                if not noarg.access & ACC_PUBLIC:
                    aw_method(owner, "<init>", "()V", f"{simple}: the no-argument constructor, private in 1.20.5")
                reshapes[key] = {"desc": "()V", "ops": ["drop"],
                                 "basis": "s4net packets: 1.20.4's read constructor never read the buffer"}
                fate(r, "reshape", "buffer never read: no-argument constructor")
                continue
            fields = instance_fields(w)
            fc = field_constructor(w, fields)
            fdesc = fc.desc if fc is not None else None
            getters = [getter_of(w, f) for f in fields]
            if fc is None or None in getters or decode_expr(w, "buf") is None:
                fate(r, "design", "no field constructor with getters to spread a decoded packet into")
                continue
            if not fc.access & ACC_PUBLIC:
                aw_method(owner, "<init>", fdesc, f"{simple}: the constructor over its fields, private in 1.20.5")
            fac = factory(w, simple)
            ops = []
            params = classfile.split_args(fdesc)[0]
            for k, (f, g) in enumerate(zip(fields, getters)):
                hname = f"cbSpread{simple}_{k}"
                if len(fields) == 1:
                    src = f"{fac}(buf)"
                elif k == 0:
                    src = f"CbNetSpread.cbFirst(buf, CbNetPacketReaders::{fac})"
                else:
                    src = f"CbNetSpread.<{jtype('L' + owner + ';')}>cbNext(buf, {'true' if k == len(fields) - 1 else 'false'})"
                if hname not in [x[0] for x in readers]:
                    readers.append((hname, f"    /** super(buf) of a 1.20.4 subclass of {simple}: argument {k} ({f[0]}) */\n"
                                           f"    public static {jtype(params[k])} {hname}(class_2540 buf) {{\n"
                                           f"        return {src}.{g}();\n    }}\n"))
                ops.append(f"conv:0 {READERS}#{hname}({BUF}){params[k]}")
            reshapes[key] = {"desc": fdesc, "ops": ops,
                             "basis": "s4net packets: no read constructor in 1.20.5; the constructor over the fields, each the field of one packet decoded from the buffer"}
            fate(r, "spread", f"{len(fields)} fields")
            continue

        if name == "<init>" and desc == "()V" and usage in ("new", "super-ctor"):
            wc = method(w, "<init>", "()V")
            inst = [f for f in w.fields if f[2] & ACC_STATIC and f[1] == "L" + owner + ";"]
            if wc is None:
                fate(r, "design", "no no-argument constructor")
                continue
            if usage == "super-ctor":
                if not wc.access & ACC_PUBLIC:
                    aw_method(owner, "<init>", "()V", f"{simple}: the no-argument constructor, private in 1.20.5")
                fate(r, "aw", "no-argument constructor, private")
                continue
            if len(inst) != 1:
                fate(r, "design", "a private constructor without one instance")
                continue
            fname = f"cbNew{simple}"
            if fname not in [x[0] for x in readers]:
                readers.append((fname, f"    /** new {simple}(): 1.20.5 keeps one instance, and its unit codec encodes only that one */\n"
                                       f"    public static {jtype('L' + owner + ';')} {fname}() {{\n"
                                       f"        return {jtype('L' + owner + ';')}.{inst[0][0]};\n    }}\n"))
            ctor_redirects[key] = f"{READERS}#{fname}"
            fate(r, "factory", "the unit packet's instance")
            continue

        if usage == "call-static" and r[4] == "ACCESS":
            wm = method(w, name, desc)
            if wm is not None and wm.access & ACC_STATIC and not wm.access & ACC_PUBLIC:
                aw_method(owner, name, desc, f"{simple}: a static reader, private in 1.20.5")
                fate(r, "aw", "static, private")
                continue
        fate(r, "other", "")

    # ---- write everything out
    src = os.path.join(layer, "src", PKG)
    for f in os.listdir(os.path.join(src, "mixin")):
        if f.startswith("CbNetWrite") and f.endswith(".java"):
            os.remove(os.path.join(src, "mixin", f))
    for owner, (simple, body, acc) in sorted(mixins.items()):
        t = jtype("L" + owner + ";")
        imp = "import net.minecraft.class_2540;\n" + ("import " + jtype("L" + BUFS + ";") + ";\n" if body and body[1] == REG_BUF else "")
        mod = "public " + ("final " if acc & ACC_FINAL else "")
        if body is None:
            code = "        // 1.20.4's write wrote nothing for this packet\n"
            doc = "writes nothing, as 1.20.4's did"
        else:
            arg = "CbNetBufs.cbRegistryBuf(buf)" if body[1] == REG_BUF else "buf"
            code = f"        {t}.{body[0]}.encode({arg}, ({t}) (Object) this);\n"
            doc = "encodes this packet with its STREAM_CODEC, as 1.20.5 writes it" + (" (through a RegistryFriendlyByteBuf view)" if body[1] == REG_BUF else "")
        java = (f"package {PKG.replace('/', '.')}.mixin;\n\n{imp}import org.spongepowered.asm.mixin.Mixin;\n"
                f"import {jtype('L' + LEGACY + ';')};\n\n"
                f"/** Generated by core/tools/gen_packet_bridges.py: {names.mojang(owner)}.write(FriendlyByteBuf), 1.20.4's shape. */\n"
                f"@Mixin({t}.class)\npublic abstract class CbNetWrite{simple} implements CbNetLegacyPacket {{\n\n"
                f"    /** was write(FriendlyByteBuf): {doc} */\n"
                f"    @Override\n    {mod}void {WRITE}(class_2540 buf) {{\n{code}    }}\n}}\n")
        open(os.path.join(src, "mixin", f"CbNetWrite{simple}.java"), "w", encoding="utf-8", newline="\n").write(java)

    body = "".join(x[1] + "\n" for x in readers).rstrip("\n") + "\n"
    rt = (f"package {PKG.replace('/', '.')}.rt;\n\nimport net.minecraft.class_2540;\n\n"
          "/**\n * Generated by core/tools/gen_packet_bridges.py (area s4net): 1.20.4's packet read constructors where\n"
          " * 1.20.5 has none -- each packet decoded with its STREAM_CODEC -- and the unit packets' instances.\n"
          " * A subclass's super(buf) takes the fields of one packet decoded from the buffer (CbNetSpread).\n */\n"
          f"public final class CbNetPacketReaders {{\n\n{body}\n    private CbNetPacketReaders() {{\n    }}\n}}\n")
    open(os.path.join(src, "rt", "CbNetPacketReaders.java"), "w", encoding="utf-8", newline="\n").write(rt)

    frag = {"covers": sorted(covers), "ctorRedirects": dict(sorted(ctor_redirects.items())),
            "superCtorReshapes": dict(sorted(reshapes.items()))}
    with open(wiring + ".d/s4net-packets.json", "w", encoding="utf-8", newline="\n") as o:
        json.dump(frag, o, indent=1, ensure_ascii=False)
        o.write("\n")

    awp = os.path.join(layer, "resources", "cb-step-1.20.5.accesswidener")
    text = open(awp, encoding="utf-8").read()
    if AW_BEGIN in text:
        text = text[:text.index(AW_BEGIN)] + text[text.index(AW_END) + len(AW_END):].lstrip("\n")
    text = text.rstrip("\n") + "\n\n" + AW_BEGIN + "\n"
    for line, why in sorted(aw):
        text += f"# {why}\n{line}\n"
    text += AW_END + "\n"
    open(awp, "w", encoding="utf-8", newline="\n").write(text)

    cfgp = os.path.join(layer, "resources", "cb-step-1.20.5.mixins.json")
    cfg = json.load(open(cfgp, encoding="utf-8"))
    cfg["mixins"] = [m for m in cfg.get("mixins", []) if not m.startswith("CbNetWrite")] \
        + [f"CbNetWrite{s}" for s, _, _ in sorted(mixins.values())]
    with open(cfgp, "w", encoding="utf-8", newline="\n") as o:
        json.dump(cfg, o, indent=2)
        o.write("\n")

    with open(report, "w", encoding="utf-8") as o:
        o.write("usage\towner\tname\tdesc\tfate\tdetail\n")
        for f in fates:
            o.write("\t".join(f) + "\n")
    import collections
    print(collections.Counter(f[4] for f in fates))
    print(f"{len(mixins)} write mixins, {len(ctor_redirects)} factories, {len(reshapes)} reshapes, {len(aw)} access widener lines")


if __name__ == "__main__":
    main()
