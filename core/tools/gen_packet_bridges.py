"""The 1.20.4 packet surface on 1.20.5's stream codecs (area s4net of step 1.20.4 -> 1.20.5).

1.20.5 builds every packet from a StreamCodec. The read constructor P(FriendlyByteBuf) became
private, or takes a RegistryFriendlyByteBuf, or is gone where a record's codec reads its components;
write(FriendlyByteBuf) left the Packet interface, and each packet's own writer is private, under
another name, reached only through the class's STREAM_CODEC. For every damage row of that kind
(core/segments/damage/1.20.4__1.20.5.damage.tsv: P.<init>(FriendlyByteBuf), P.write(FriendlyByteBuf),
the unit packets' no-argument constructors, the movement packets' static readers) this decides, from
both releases' bytecode, how 1.20.4's member comes back:

  write(buf)      a mixin restores public write(FriendlyByteBuf) on P (covers): the packet is encoded
                  with P's own STREAM_CODEC, as 1.20.5 writes it (through a RegistryFriendlyByteBuf view
                  where the codec wants one); a write that wrote nothing in 1.20.4 (bundle and unit
                  packets) writes nothing. The packet then implements CbNetLegacyPacket, which a call of
                  Packet.write(buf) through the interface dispatches to. A writer 1.20.5 kept under the
                  same name, only private, is opened by the layer's access widener instead.
  new P(buf)      private P(FriendlyByteBuf): the access widener opens it. P(RegistryFriendlyByteBuf):
                  opened and reshaped, the buffer passed as a RegistryFriendlyByteBuf view. No read
                  constructor: a factory decodes with P's STREAM_CODEC (ctorRedirects).
  super(buf)      as new, where a read constructor is there; otherwise the constructor that takes P's
                  fields in order, each argument the field of one packet decoded from the buffer (records:
                  the canonical constructor and the component accessors); where 1.20.4's read constructor
                  never read the buffer, the no-argument constructor with the buffer dropped.
  new P()         a unit packet (1.20.5 keeps one instance and its codec encodes only that one): the
                  factory answers the instance; a subclass's super() gets the private constructor opened.
  P.read(buf)     a static reader 1.20.5 made private: opened.
  records         the 20 classes 1.20.5 turned into final records (RECORDS, RECORD_CTORS below): reopened
                  (extendable), each getter renamed to its component accessor -- or, where the accessor
                  answers another type, called through a converting static -- with an override hook so a
                  1.20.4 subclass's getter answers vanilla's accessor calls, and the constructors whose
                  shape changed reshaped.

Anything else in those rows is reported as "design" and left to the hand-written wiring. Members the
hand-written wiring (the step's other fragments) handles already are skipped.

Outputs (regenerate, never hand-edit):
  <layer>/src/.../mixin/CbNetWrite<Name>.java      one per packet whose write comes back by mixin
  <layer>/src/.../rt/CbNetPacketReaders.java       the factories and the spread helpers
  <layer>/src/.../rt/CbNetRecordPackets.java       the records' converting getters
  <layer>/src/.../mixin/CbNetRecordFields<Name>    the record fields those read for a subclass's super call
  <wiring>.d/s4net-packets.json                    covers, ctorRedirects, superCtorReshapes, the records' renames,
                                                   hooks and redirects
  <layer>/resources/cb-step-1.20.5.accesswidener    the block between the s4net-packets markers
  <layer>/resources/cb-step-1.20.5.mixins.json      the CbNetWrite* entries of "mixins" (others kept)

  python gen_packet_bridges.py <damage.tsv> <V code jar> <W code jar> <layer dir> <step wiring.json> <class names.tsv> <report.tsv>
"""
