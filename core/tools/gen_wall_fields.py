"""Static fields the namespace wall narrowed: 1.21.11 reads them with a type 26.1 no longer declares.

26.1 kept many registry constants under the same (translated) name and narrowed their declared type
to a subtype (Potions.WATER: Holder<Potion> -> Holder.Reference<Potion>; the same for most sound,
loot-function and worldgen constants). A field reference links by name AND descriptor, so 1.21.11's
GETSTATIC of the wider type finds nothing. The value 26.1 holds is one of the old type (a subtype),
so the read is answered by a getter of the old type returning 26.1's field (fieldGetters): the same
object, no conversion.

Only get-static rows of the step's damage table are considered, and only where the wall table
names the field, 26.1 declares it public static on the translated owner, and its type is assignable
to the translated 1.21.11 type (checked through 26.1's class hierarchy). Everything else is left to
hand bridging and listed in the report.

  python gen_wall_fields.py <damage.tsv> <V jar> <W jar> <wall table> <fragment.json> <runtime class> <src root> <report.tsv>
      runtime class: internal name, e.g. top/dext/centurybridge/step/v26_1/rt/CbWallFields

Writes the runtime class, the fragment ({"fieldGetters": {...}}) and the report; nothing else.

Regenerating (from the repo root):
  python3 core/tools/gen_wall_fields.py core/segments/damage/1.21.11__26.1.damage.tsv \
      data/jars/client-1.21.11-intermediary.jar data/jars/client-26.1.jar \
      data/mappings/inter-to-mojang-1.21.11-26.1.tsv \
      core/segments/steps/1.21.11__26.1.json.d/swall-fields-gen.json \
      top/dext/centurybridge/step/v26_1/rt/CbWallFields core/shims/steps/26.1/src <tmp>/fields-report.tsv
"""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import classfile  # noqa: E402
from gen_step_reshapes import Hierarchy, Wall, load  # noqa: E402

ACC_PUBLIC, ACC_STATIC = 0x0001, 0x0008


def java_type(desc):
    """a field descriptor as Java source (erased; nested classes with dots)"""
    dims = 0
    while desc.startswith("["):
        dims += 1
        desc = desc[1:]
    prim = {"Z": "boolean", "B": "byte", "C": "char", "S": "short", "I": "int", "J": "long", "F": "float", "D": "double"}
    t = prim[desc] if desc in prim else desc[1:-1].replace("/", ".").replace("$", ".")
    return t + "[]" * dims


def main():
    dmg, vjar, wjar, table, frag, rtcls, src, report = sys.argv[1:9]
    wall = Wall(table)
    fmap = {}
    for line in open(table, encoding="utf-8"):
        f = line.rstrip("\n").split("\t")
        if len(f) >= 3 and f[0] == "F":
            fmap[f[1]] = f[2].rsplit(".", 1)[1]
    V = load(vjar, False)
    W = load(wjar, False)
    hw = Hierarchy(W)
    getters, rep = {}, []
    seen = set()
    for line in open(dmg, encoding="utf-8"):
        r = line.rstrip("\n").split("\t")
        if len(r) < 4 or r[0] != "get-static":
            continue
        owner, name, desc = r[1], r[2], r[3]
        key = (owner, name, desc)
        if key in seen:
            continue
        seen.add(key)
        wowner = wall.cls(owner)
        wname = fmap.get(f"{owner}.{name}")
        if not wname:
            rep.append((owner, name, desc, "no wall-table row for the field"))
            continue
        wc = W.get(wowner)
        if not wc:
            rep.append((owner, name, desc, f"26.1 has no {wowner}"))
            continue
        hit = next((f for f in wc.fields if f[0] == wname), None)
        if not hit:
            rep.append((owner, name, desc, f"26.1 {wowner} declares no {wname}"))
            continue
        wdesc, acc = hit[1], hit[2]
        if (acc & (ACC_PUBLIC | ACC_STATIC)) != (ACC_PUBLIC | ACC_STATIC):
            rep.append((owner, name, desc, f"26.1 {wowner}.{wname} is not public static"))
            continue
        tv = wall.desc(desc)
        if wdesc == tv:
            rep.append((owner, name, desc, "same type in 26.1: not narrowed (damage of another kind)"))
            continue
        if not hw.assignable(wdesc, tv):
            rep.append((owner, name, desc, f"26.1 type {wdesc} is no {tv}: not a narrowing"))
            continue
        getters[name] = (owner, desc, wowner, wname, tv)
    pkg, simple = rtcls.rsplit("/", 1)
    lines = [
        "package " + pkg.replace("/", ".") + ";",
        "",
        "/**",
        " * Generated by core/tools/gen_wall_fields.py -- do not edit; regenerate with the command in its header.",
        " *",
        " * 1.21.11 static fields 26.1 kept under the wall table's name with a narrower declared type",
        " * (Holder -> Holder.Reference and the like): each getter answers 26.1's field as the 1.21.11 type.",
        " */",
        "@SuppressWarnings({\"rawtypes\", \"unused\"})",
        "public final class " + simple + " {",
        "",
        "    private " + simple + "() {",
        "    }",
    ]
    for name in sorted(getters):
        owner, desc, wowner, wname, tv = getters[name]
        lines += ["",
                  f"    /** {owner}.{name} ({wowner}.{wname}) */",
                  f"    public static {java_type(tv)} {name}() {{",
                  f"        return {java_type('L' + wowner + ';')}.{wname};",
                  "    }"]
    lines += ["}", ""]
    path = os.path.join(src, rtcls + ".java")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write("\n".join(lines))
    out = {"fieldGetters": {f"{o}.{n}:{d}": rtcls for n, (o, d, _, _, _) in sorted(getters.items())}}
    with open(frag, "w", encoding="utf-8", newline="\n") as fh:
        json.dump(out, fh, indent=1)
        fh.write("\n")
    with open(report, "w", encoding="utf-8", newline="\n") as fh:
        for row in rep:
            fh.write("\t".join(row) + "\n")
    print(f"{len(getters)} narrowed static fields -> {frag}; {len(rep)} left (report {report})")


if __name__ == "__main__":
    main()
