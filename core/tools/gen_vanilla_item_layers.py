"""Generate res/VanillaItemLayers.java: the highest tint index each 1.20.1 vanilla item
model renders with, through its parent chain (layerN textures of item/generated, a face's
tintindex). A mod item model that names one of them as its parent -- template_spawn_egg,
leather armour, potions, trims -- draws that many tinted layers without saying so in its
own file; the converter's item model definitions need one tint per index.

  python gen_vanilla_item_layers.py <client-1.20.1.jar> <out.java>
"""
import json
import re
import sys
import zipfile


def main():
    jar, out = sys.argv[1], sys.argv[2]
    z = zipfile.ZipFile(jar)
    models = {}
    for n in z.namelist():
        if n.startswith("assets/minecraft/models/") and n.endswith(".json"):
            models[n[len("assets/minecraft/models/"):-len(".json")]] = json.loads(z.read(n))

    def norm(ref):
        return ref.split(":", 1)[1] if ":" in ref else ref

    def highest(name, seen=()):
        m = models.get(name)
        if m is None or name in seen:
            return -1
        mx = -1
        for k in (m.get("textures") or {}):
            if re.fullmatch(r"layer\d+", k):
                mx = max(mx, int(k[5:]))
        for el in m.get("elements") or []:
            for f in (el.get("faces") or {}).values():
                if "tintindex" in f:
                    mx = max(mx, f["tintindex"])
        p = m.get("parent")
        if p and not p.startswith("builtin/"):
            mx = max(mx, highest(norm(p), seen + (name,)))
        return mx

    rows = sorted((n, highest(n)) for n in models if n.startswith("item/"))
    rows = [(n, v) for n, v in rows if v >= 1]
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write("package top.dext.centurybridge.res;\n\n")
        f.write("/**\n * Generated by core/tools/gen_vanilla_item_layers.py from the 1.20.1 client jar -- do not edit.\n")
        f.write(" * The highest tint index of every 1.20.1 vanilla item model that has more than one\n")
        f.write(" * (through its parent chain); every other vanilla item model has at most index 0.\n */\n")
        f.write("public final class VanillaItemLayers {\n\n")
        f.write("    private static final java.util.Map<String, Integer> HIGHEST = new java.util.HashMap<>();\n\n")
        f.write("    static {\n")
        for n, v in rows:
            f.write(f"        HIGHEST.put(\"{n}\", {v});\n")
        f.write("    }\n\n")
        f.write("    /** the highest tint index of minecraft:{@code path} (\"item/...\"), 0 when it has one layer or is unknown */\n")
        f.write("    public static int highest(String path) {\n")
        f.write("        return HIGHEST.getOrDefault(path, 0);\n")
        f.write("    }\n\n")
        f.write("    private VanillaItemLayers() {\n    }\n}\n")
    print(f"{len(rows)} vanilla item models with a tint index above 0 -> {out}")


if __name__ == "__main__":
    main()
