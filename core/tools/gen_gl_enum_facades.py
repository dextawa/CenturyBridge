"""gen_gl_enum_facades.py: layer facades for the GlStateManager enums 1.21.5 dropped (step 1.21.4 -> 1.21.5).

1.21.4 declared SourceFactor, DestFactor and LogicOp inside GlStateManager (class_4535 / class_4534 / class_1030), each
constant carrying its GL enum in a public int field. 1.21.5 dropped them (the top-level platform/SourceFactor, DestFactor
and LogicOp it added carry no GL value; LogicOp keeps only NONE / OR_REVERSE), and RenderSystem's blendFunc / logicOp
that took them. The facades give back each enum with 1.21.4's constants in 1.21.4's order, under 1.21.4's names, with
1.21.4's GL value, read off 1.21.4's <clinit> (javap): name(), ordinal(), valueOf and values() answer as before.

    python3 core/tools/gen_gl_enum_facades.py <V code jar> <layer facade dir>
"""
import os, re, subprocess, sys

PKG = "top.dext.centurybridge.step.v1_21_5.facade"
ENUMS = {
    "class_4535": ("SourceFactor", "value"),
    "class_4534": ("DestFactor", "value"),
    "class_1030": ("LogicOp", "field_5108"),
}


def constants(jar, cls):
    out = subprocess.run(["javap", "-c", "-p", "-cp", jar, f"com.mojang.blaze3d.platform.GlStateManager${cls}"],
                         capture_output=True, text=True, errors="replace").stdout
    body = out[out.index("static {};"):]
    rows, cur = [], None
    for line in body.splitlines():
        if "// String " in line and cur is None:
            cur = {"name": line.split("// String ", 1)[1].strip(), "ints": []}
            continue
        if cur is not None:
            v = re.search(r"(?:sipush|bipush)\s+(-?\d+)|iconst_(m1|\d)|ldc(?:_w)?\s+#\d+\s+// int (-?\d+)", line)
            if v:
                g = next(x for x in v.groups() if x is not None)
                cur["ints"].append(-1 if g == "m1" else int(g))
            p = re.search(r"putstatic .*// Field (\w+):", line)
            if p:
                cur["field"] = p.group(1)
                rows.append(cur)
                cur = None
    return rows


def main():
    jar, outdir = sys.argv[1:3]
    for cls, (mojang, valname) in ENUMS.items():
        rows = constants(jar, cls)
        fname = f"GlStateManager${cls}"
        lines = [f"package {PKG};", "", "import net.fabricmc.api.EnvType;", "import net.fabricmc.api.Environment;", "",
                 "/**",
                 f" * Facade for 1.21.4's com/mojang/blaze3d/platform/GlStateManager${cls} (GlStateManager.{mojang}), which 1.21.5",
                 " * dropped: 1.21.4's constants in 1.21.4's order with their GL values (generated by",
                 " * core/tools/gen_gl_enum_facades.py from 1.21.4's bytecode; regenerate, never hand-edit).",
                 " */", "@Environment(EnvType.CLIENT)", f"public enum {fname} {{"]
        for i, r in enumerate(rows):
            ordinal, value = r["ints"][0], r["ints"][1]
            assert ordinal == i, (cls, r)
            lines.append(f"    {r['name']}({value}){',' if i + 1 < len(rows) else ';'}")
        lines.append("")
        for r in rows:
            if r["field"] != r["name"]:
                lines.append(f"    /** 1.21.4's intermediary name of {r['name']} */")
                lines.append(f"    public static final {fname} {r['field']} = {r['name']};")
        lines += ["", f"    /** the GL enum ({mojang}.value in 1.21.4) */", f"    public final int {valname};", "",
                  f"    {fname}(int {valname}) {{", f"        this.{valname} = {valname};", "    }", "}", ""]
        path = os.path.join(outdir, fname + ".java")
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write("\n".join(lines))
        print(f"{fname}: {len(rows)} constants -> {path}")


if __name__ == "__main__":
    main()
