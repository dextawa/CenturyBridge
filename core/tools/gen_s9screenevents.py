#!/usr/bin/env python3
"""s9 (step 1.21.8 -> 1.21.9): Fabric API screen input events, generated.

Fabric API 0.134 (1.21.9) took the screen keyboard / mouse event listeners onto 1.21.9's input records:
ScreenKeyboardEvents.*(screen, key, scancode, modifiers) -> (screen, KeyEvent); ScreenMouseEvents click / release
(screen, x, y, button) -> (screen, MouseButtonEvent), drag (screen, x, y, button, dx, dy) -> (screen,
MouseButtonEvent, dx, dy). The After* mouse listeners now answer whether they consumed the input and are told whether
it already was ((.., consumed)Z; ScreenEventFactory ORs the answers); a 1.21.8 After* listener could not consume, so
it answers false (javap: ScreenEventFactory.createAfterMouseClickEvent and the others).

For each listener interface this writes:
  - lambdaAdapters: a 1.21.8 lambda / method reference of the interface becomes a 1.21.9 listener over it;
  - overrideHooks (bridge mode, adapter): a 1.21.8 class implementing the interface answers 1.21.9's method;
  - callReshapes: a 1.21.8 call of the listener (an invoker) builds the record (CbInput) and, for After*, passes
    consumed = false and drops the answer.
and rt/CbScreenEvents.java (the Legacy* interfaces, adapters and bridges).

  python3 core/tools/gen_s9screenevents.py <out fragment.json> <out CbScreenEvents.java>
"""
import json
import sys

PKG = "net/fabricmc/fabric/api/client/screen/v1/"
RT = "top/dext/centurybridge/step/v1_21_9/rt/"
CB = RT + "CbScreenEvents"
IN = RT + "CbInput"
SCREEN = "Lnet/minecraft/class_437;"
KEY = "Lnet/minecraft/class_11908;"
MOUSE = "Lnet/minecraft/class_11909;"

# (holder, interface, method, kind, when) -- kind: key / click / drag / scroll
EVENTS = []
for when in ("Allow", "Before", "After"):
    low = when[0].lower() + when[1:]
    for what in ("Press", "Release"):
        EVENTS.append(("ScreenKeyboardEvents", f"{when}Key{what}", f"{low}Key{what}", "key", when))
    for what in ("Click", "Release"):
        EVENTS.append(("ScreenMouseEvents", f"{when}Mouse{what}", f"{low}Mouse{what}", "click", when))
    EVENTS.append(("ScreenMouseEvents", f"{when}MouseDrag", f"{low}MouseDrag", "drag", when))
EVENTS.append(("ScreenMouseEvents", "AfterMouseScroll", "afterMouseScroll", "scroll", "After"))

V_ARGS = {"key": "III", "click": "DDI", "drag": "DDIDD", "scroll": "DDDD"}
J_V_PARAMS = {"key": "int key, int scancode, int modifiers", "click": "double x, double y, int button",
              "drag": "double x, double y, int button, double dx, double dy",
              "scroll": "double x, double y, double h, double v"}


def consumes(kind, when):
    """1.21.9's After* mouse listeners take and answer `consumed`"""
    return when == "After" and kind != "key"


def main():
    out, java = sys.argv[1:3]
    frag = {"callReshapes": {}, "overrideHooks": [], "lambdaAdapters": {}}
    j = ["package top.dext.centurybridge.step.v1_21_9.rt;", "",
         "// generated by core/tools/gen_s9screenevents.py -- regenerate, never hand-edit", "",
         "import net.fabricmc.api.EnvType;", "import net.fabricmc.api.Environment;",
         "import net.fabricmc.fabric.api.client.screen.v1.ScreenKeyboardEvents;",
         "import net.fabricmc.fabric.api.client.screen.v1.ScreenMouseEvents;",
         "import net.minecraft.class_11908;", "import net.minecraft.class_11909;", "import net.minecraft.class_437;", "",
         "/** Fabric API's screen input listeners in 1.21.8's shape (gen_s9screenevents.py: what changed and why) */",
         "@Environment(EnvType.CLIENT)", "public final class CbScreenEvents {", "    private CbScreenEvents() {", "    }"]
    for holder, iface, m, kind, when in EVENTS:
        owner = PKG + holder + "$" + iface
        cons = consumes(kind, when)
        vret = "Z" if when == "Allow" else "V"
        wret = "Z" if when == "Allow" or cons else "V"
        wargs = {"key": KEY, "click": MOUSE, "drag": MOUSE + "DD", "scroll": "DDDD"}[kind] + ("Z" if cons else "")
        vdesc = f"({SCREEN}{V_ARGS[kind]}){vret}"
        wdesc = f"({SCREEN}{wargs}){wret}"
        legacy = f"Legacy{iface}"
        jtype = f"{holder}.{iface}"
        vret_j = "boolean" if vret == "Z" else "void"
        wret_j = "boolean" if wret == "Z" else "void"
        if kind == "key":
            wparams, vvals = ["class_11908 e"], "e.comp_4795(), e.comp_4796(), e.comp_4797()"
        elif kind == "click":
            wparams, vvals = ["class_11909 e"], "e.comp_4798(), e.comp_4799(), e.method_74245()"
        elif kind == "drag":
            wparams, vvals = ["class_11909 e", "double dx", "double dy"], "e.comp_4798(), e.comp_4799(), e.method_74245(), dx, dy"
        else:
            wparams, vvals = ["double x", "double y", "double h", "double v"], "x, y, h, v"
        if cons:
            wparams.append("boolean consumed")
        wnames = ", ".join(p.split()[-1] for p in wparams)
        call_v = f"fn.{m}(screen, {vvals});"
        if cons:
            lam = [f"            {call_v}", "            return false;"]
            brg = [f"        {call_v}", "        return false;"]
        elif wret_j == "boolean":
            lam = [f"            return {call_v}"]
            brg = [f"        return {call_v}"]
        else:
            lam = [f"            {call_v}"]
            brg = [f"        {call_v}"]
        j += ["", f"    /** {jtype}.{m} in 1.21.8's shape */",
              f"    public interface {legacy} {{", f"        {vret_j} {m}(class_437 screen, {J_V_PARAMS[kind]});", "    }", "",
              f"    public static {jtype} adapt{iface}({legacy} fn) {{",
              f"        return (screen, {wnames}) -> {{"] + lam + ["        };", "    }", "",
              f"    public static {wret_j} cb{iface}({legacy} fn, class_437 screen, {', '.join(wparams)}) {{"] + brg + ["    }"]
        frag["lambdaAdapters"][f"{owner}.{m}{vdesc}"] = {
            "adapt": f"{CB}#adapt{iface}(L{CB}${legacy};)L{owner};", "iface": f"{CB}${legacy}"}
        frag["overrideHooks"].append({
            "adapter": f"{CB}${legacy}",
            "basis": f"s9 fapi screen: {holder}.{iface}.{m} takes 1.21.9's input record; the 1.21.8 implementation gets "
                     "1.21.8's values" + (" and answers false (it could not consume)" if cons else ""),
            "bridge": f"{CB}.cb{iface}(L{CB}${legacy};{wdesc[1:]}",
            "guard": RT + "Guard", "new": m + wdesc, "old": m + vdesc, "onlyUnder": owner})
        if kind == "key":
            ops = ["keep:0", f"conv:1,2,3 {IN}#cbKey(III){KEY}"]
        elif kind == "click":
            ops = ["keep:0", f"conv:1,2,3 {IN}#cbClick(DDI){MOUSE}"]
        elif kind == "drag":
            ops = ["keep:0", f"conv:1,2,3 {IN}#cbClick(DDI){MOUSE}", "keep:4", "keep:5"]
        else:
            ops = ["keep:0", "keep:1", "keep:2", "keep:3", "keep:4"]
        entry = {"basis": f"s9 fapi screen: {holder}.{iface}.{m} takes 1.21.9's input record (CbInput)", "desc": wdesc, "ops": ops}
        if cons:
            ops.append(f"push {CB}#notConsumed()Z")
            entry["ret"] = "pop"
            entry["basis"] += "; a 1.21.8 caller had nothing consumed and takes no answer"
        frag["callReshapes"][f"{owner}.{m}{vdesc}"] = entry
    j += ["", "    /** consumed = false: what a 1.21.8 After* call passes (1.21.8 had no such flag) */",
          "    public static boolean notConsumed() {", "        return false;", "    }", "}", ""]
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        json.dump(frag, f, indent=1)
        f.write("\n")
    with open(java, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(j))
    print(f"{len(frag['callReshapes'])} callReshapes, {len(frag['overrideHooks'])} overrideHooks, "
          f"{len(frag['lambdaAdapters'])} lambdaAdapters -> {out}")


if __name__ == "__main__":
    main()
