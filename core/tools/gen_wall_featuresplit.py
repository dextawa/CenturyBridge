"""gen_wall_featuresplit.py: the 26.1 layer's mixins for 1.21.11 feature renderers whose render(..) 26.1 split
into renderSolid(..) + renderTranslucent(..) with the same arguments (rt/CbWallLegacySplit). Writes one mixin per
class into core/shims/steps/26.1/src/.../mixin/ and prints the covers keys. Run from the repo root."""
import os

PKG = 'top.dext.centurybridge.step.v26_1'
OUT = 'core/shims/steps/26.1/src/top/dext/centurybridge/step/v26_1/mixin/'
C, BS, OUTL = ('SubmitNodeCollection', 'net.minecraft.client.renderer.SubmitNodeCollection', 'Lnet/minecraft/class_11788;'), \
    ('MultiBufferSource.BufferSource', 'net.minecraft.client.renderer.MultiBufferSource', 'Lnet/minecraft/class_4597$class_4598;'), \
    ('OutlineBufferSource', 'net.minecraft.client.renderer.OutlineBufferSource', 'Lnet/minecraft/class_4618;')
# (26.1 class, 1.21.11 intermediary class, its render id, parameters)
SPLITS = [
    ('CustomFeatureRenderer', 'class_11682', 'method_72999', [C, BS]),
    ('ItemFeatureRenderer', 'class_11687', 'method_73010', [C, BS, OUTL]),
    ('ModelFeatureRenderer', 'class_11683', 'method_73001', [C, BS, OUTL, BS]),
    ('ModelPartFeatureRenderer', 'class_11793', 'method_73543', [C, BS, OUTL, BS]),
    ('ParticleFeatureRenderer', 'class_11977', 'method_74407', [C]),
]

for cls, inter, mid, params in SPLITS:
    names = ['collection', 'bufferSource', 'outline', 'crumbling'][:len(params)]
    decl = ', '.join(f'{p[0]} {n}' for p, n in zip(params, names))
    args = ', '.join(names)
    classes = ', '.join(p[0] + '.class' for p in params)
    imports = sorted({p[1] for p in params} | {'net.minecraft.client.renderer.feature.' + cls})
    mixin = f'CbWall{cls}SplitMixin'
    src = f'''package {PKG}.mixin;

import net.fabricmc.api.EnvType;
import net.fabricmc.api.Environment;
{chr(10).join('import ' + i + ';' for i in imports)}
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.Shadow;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;
import {PKG}.rt.CbWallLegacySplit;

/**
 * 1.21.11's {cls}.render(..) ({inter}.{mid}), which 26.1 split into renderSolid(..) and renderTranslucent(..) with
 * the same arguments: given back as both halves in turn; a subclass overriding it is called once per frame from
 * vanilla's first half (rt/CbWallLegacySplit). Generated by core/tools/gen_wall_featuresplit.py.
 */
@Environment(EnvType.CLIENT)
@Mixin({cls}.class)
public abstract class {mixin} {{

    @Shadow
    public abstract void renderSolid({decl});

    @Shadow
    public abstract void renderTranslucent({decl});

    /** 1.21.11 {cls}.render ({inter}.{mid}) */
    public void render({decl}) {{
        CbWallLegacySplit.enter(this);
        try {{
            renderSolid({args});
            renderTranslucent({args});
        }} finally {{
            CbWallLegacySplit.exit(this);
        }}
    }}

    @Inject(method = "renderSolid", at = @At("HEAD"), cancellable = true)
    private void cb$legacySolid({decl}, CallbackInfo ci) {{
        if (CbWallLegacySplit.legacy(this, {cls}.class, "render", {classes})) {{
            ci.cancel();
            render({args});
        }}
    }}

    @Inject(method = "renderTranslucent", at = @At("HEAD"), cancellable = true)
    private void cb$legacyTranslucent({decl}, CallbackInfo ci) {{
        if (CbWallLegacySplit.legacy(this, {cls}.class, "render", {classes})) {{
            ci.cancel();
        }}
    }}
}}
'''
    open(OUT + mixin + '.java', 'w', encoding='utf-8', newline='\n').write(src)
    desc = '(' + ''.join(p[2] for p in params) + ')V'
    print(f'net/minecraft/{inter}.{mid}{desc}\t{mixin}')
