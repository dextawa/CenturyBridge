"""gen_wall_featuresplit.py: the 26.1 layer's mixins for 1.21.11 feature renderers whose render(..) 26.1 split
into renderSolid(..) + renderTranslucent(..) with the same arguments (rt/CbWallLegacySplit). Writes per class a
restorer mixin (the restored render(..), at CbVanillaReads.PRIORITY so mods' injectors can reach it) and a reads
mixin (default priority: the injectors into 26.1's renderSolid / renderTranslucent that hand vanilla's call to a
subclass's render override), both into core/shims/steps/26.1/src/.../mixin/, and rt/CbWallFeatureSplits.java (the
restored render(..) as an interface per class, through which the reads mixin calls it). Prints the covers keys. Run
from the repo root."""

PKG = 'top.dext.centurybridge.step.v26_1'
OUT = 'core/shims/steps/26.1/src/top/dext/centurybridge/step/v26_1/'
C, BS, OUTL = ('SubmitNodeCollection', 'net.minecraft.client.renderer.SubmitNodeCollection', 'Lnet/minecraft/class_11788;'), \
    ('MultiBufferSource.BufferSource', 'net.minecraft.client.renderer.MultiBufferSource', 'Lnet/minecraft/class_4597$class_4598;'), \
    ('OutlineBufferSource', 'net.minecraft.client.renderer.OutlineBufferSource', 'Lnet/minecraft/class_4618;')
# (26.1 class, 1.21.11 intermediary class, its render id, parameters)
SPLITS = [
    ('CustomFeatureRenderer', 'class_11682', 'method_72999', [C, BS]),
    ('ItemFeatureRenderer', 'class_11687', 'method_73010', [C, BS, OUTL]),
    ('ModelFeatureRenderer', 'class_11683', 'method_73001', [C, BS, OUTL, BS]),
    ('ModelPartFeatureRenderer', 'class_11793', 'method_73543', [C, BS, OUTL, BS]),
    ('ParticleFeatureRenderer', 'class_11977', 'method_74407', [C]),
]

ifaces = []
iface_imports = set()
for cls, inter, mid, params in SPLITS:
    names = ['collection', 'bufferSource', 'outline', 'crumbling'][:len(params)]
    decl = ', '.join(f'{p[0]} {n}' for p, n in zip(params, names))
    args = ', '.join(names)
    classes = ', '.join(p[0] + '.class' for p in params)
    imports = sorted({p[1] for p in params} | {'net.minecraft.client.renderer.feature.' + cls})
    iface_imports |= {p[1] for p in params}
    legacy = f'{cls}Legacy'
    ifaces.append(f'''
    /** 1.21.11 {cls}.render ({inter}.{mid}), restored by mixin/CbWall{cls}SplitMixin */
    @Environment(EnvType.CLIENT)
    public interface {legacy} {{
        void render({decl});
    }}
''')
    mixin = f'CbWall{cls}SplitMixin'
    src = f'''package {PKG}.mixin;

import net.fabricmc.api.EnvType;
import net.fabricmc.api.Environment;
{chr(10).join('import ' + i + ';' for i in imports)}
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.Shadow;
import {PKG}.rt.CbVanillaReads;
import {PKG}.rt.CbWallFeatureSplits;
import {PKG}.rt.CbWallLegacySplit;

/**
 * 1.21.11's {cls}.render(..) ({inter}.{mid}), which 26.1 split into renderSolid(..) and renderTranslucent(..) with
 * the same arguments: given back as both halves in turn; a subclass overriding it is called once per frame from
 * vanilla's first half (mixin/{mixin[:-5]}ReadsMixin, rt/CbWallLegacySplit). Generated by
 * core/tools/gen_wall_featuresplit.py.
 */
@Environment(EnvType.CLIENT)
@Mixin(value = {cls}.class, priority = CbVanillaReads.PRIORITY)
public abstract class {mixin} implements CbWallFeatureSplits.{legacy} {{

    @Shadow
    public abstract void renderSolid({decl});

    @Shadow
    public abstract void renderTranslucent({decl});

    /** 1.21.11 {cls}.render ({inter}.{mid}) */
    @Override
    public void render({decl}) {{
        CbWallLegacySplit.enter(this);
        try {{
            renderSolid({args});
            renderTranslucent({args});
        }} finally {{
            CbWallLegacySplit.exit(this);
        }}
    }}
}}
'''
    open(OUT + 'mixin/' + mixin + '.java', 'w', encoding='utf-8', newline='\n').write(src)
    reads = f'{mixin[:-5]}ReadsMixin'
    src = f'''package {PKG}.mixin;

import net.fabricmc.api.EnvType;
import net.fabricmc.api.Environment;
{chr(10).join('import ' + i + ';' for i in imports)}
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Inject;
import org.spongepowered.asm.mixin.injection.callback.CallbackInfo;
import {PKG}.rt.CbWallFeatureSplits;
import {PKG}.rt.CbWallLegacySplit;

/**
 * A 1.21.11 subclass overriding {cls}.render(..) ({inter}.{mid}, restored by {mixin}): vanilla's renderSolid calls it
 * once per frame in place of both halves and its renderTranslucent does nothing for it; a renderer without such an
 * override runs 26.1's halves untouched. Default priority: injectors into 26.1 methods. Generated by
 * core/tools/gen_wall_featuresplit.py.
 */
@Environment(EnvType.CLIENT)
@Mixin({cls}.class)
public abstract class {reads} {{

    @Inject(method = "renderSolid", at = @At("HEAD"), cancellable = true)
    private void cb$legacySolid({decl}, CallbackInfo ci) {{
        if (CbWallLegacySplit.legacy(this, {cls}.class, "render", {classes})) {{
            ci.cancel();
            ((CbWallFeatureSplits.{legacy}) (Object) this).render({args});
        }}
    }}

    @Inject(method = "renderTranslucent", at = @At("HEAD"), cancellable = true)
    private void cb$legacyTranslucent({decl}, CallbackInfo ci) {{
        if (CbWallLegacySplit.legacy(this, {cls}.class, "render", {classes})) {{
            ci.cancel();
        }}
    }}
}}
'''
    open(OUT + 'mixin/' + reads + '.java', 'w', encoding='utf-8', newline='\n').write(src)
    desc = '(' + ''.join(p[2] for p in params) + ')V'
    print(f'net/minecraft/{inter}.{mid}{desc}\t{mixin}')

src = f'''package {PKG}.rt;

import net.fabricmc.api.EnvType;
import net.fabricmc.api.Environment;
{chr(10).join('import ' + i + ';' for i in sorted(iface_imports))}

/**
 * The 1.21.11 render(..) of the feature renderers 26.1 split into renderSolid / renderTranslucent, one interface per
 * class: restored on the class by mixin/CbWall&lt;class&gt;SplitMixin, called through the interface by its ReadsMixin
 * (a mixin cannot name a member another mixin adds). Generated by core/tools/gen_wall_featuresplit.py.
 */
@Environment(EnvType.CLIENT)
public final class CbWallFeatureSplits {{
    private CbWallFeatureSplits() {{}}
{''.join(ifaces)}}}
'''
open(OUT + 'rt/CbWallFeatureSplits.java', 'w', encoding='utf-8', newline='\n').write(src)
