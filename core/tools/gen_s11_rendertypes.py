#!/usr/bin/env python3
"""Step 1.21.10 -> 1.21.11: RenderType's static factories moved to rendertype/RenderTypes (class_12249) under new
intermediary ids. Writes the layer's rt/CbRenderTypes (1.21.10's ids, each returning 1.21.11's factory) and the
fragment s11-rendertypes-gen.json (staticRedirects to it; fieldRenames of the buffer-size constants; mixinMoves
for the same-code pairs, so a mod's injector on the 1.21.10 factory moves onto the 1.21.11 one -- never for ROLE
pairs, whose 1.21.11 factory is another body).

A pair is taken only on bytecode evidence (javap -c -p -v of both code jars):
  - same Mojang name and parameter types, and the same RenderPipelines fields and render type name strings
    reached from the factory (its own fields' <clinit> stretches, own methods, lambdas); or
  - ROLE: 1.21.11 removed the pipeline and the one vanilla caller (ItemBlockRenderTypes.getMovingBlockRenderType)
    now returns the named 1.21.11 factory where 1.21.10 returned V's (javap of both bodies; CUTOUT_MIPPED folded
    into CUTOUT: 1.21.11's chunk layer switch has 4 cases where 1.21.10's had 5).
Members without evidence stay open and are listed.

    python3 core/tools/gen_s11_rendertypes.py <evidence txt> <W class_12249 javap> <V class_1921 javap>
(from the repository root; evidence: core/tools/s11_rendertype_evidence.py output,
javap -c -p of the 1.21.11 / 1.21.10 intermediary code jars)
"""
import json
import re
import sys

LAYER = 'core/shims/steps/1.21.11/src/top/dext/centurybridge/step/v1_21_11/rt/CbRenderTypes.java'
FRAG = 'core/segments/steps/1.21.10__1.21.11.json.d/s11-rendertypes-gen.json'
ROLE = {
    'method_23577': ('method_75965', 'solid -> solidMovingBlock'),
    'method_23579': ('method_75972', 'cutoutMipped -> cutoutMovingBlock'),
    'method_23581': ('method_75972', 'cutout -> cutoutMovingBlock'),
    'method_29997': ('method_76009', 'tripwire -> tripwireMovingBlock'),
}
BY_NAME = {'method_23287': ('method_76018', 'outline(Identifier): both CompositeRenderType OUTLINE.apply(texture, false), '
                            'a memoized BiFunction over the "outline" type')}
FIELDS = {
    'net/minecraft/class_1921.field_32772:I': 'field_64008',
    'net/minecraft/class_1921.field_32774:I': 'field_64009',
    'net/minecraft/class_1921.field_32775:I': 'field_64010',
}


def descs(javap):
    out = {}
    for l in open(javap, encoding='utf-8', errors='replace'):
        m = re.match(r'\s+public static net\.minecraft\.class_1921 (method_\d+)\((.*)\);', l)
        if m:
            out[m.group(1)] = [p.strip() for p in m.group(2).split(',') if p.strip()]
    return out


def jtype(p):
    return {'boolean': 'Z', 'float': 'F', 'double': 'D', 'int': 'I'}.get(p, 'L' + p.replace('.', '/') + ';')


def main():
    ev, wj = sys.argv[1], sys.argv[2]
    vd = {}
    for l in open(sys.argv[3], encoding='utf-8', errors='replace'):
        m = re.match(r'\s+public static net\.minecraft\.class_1921 (method_\d+)\((.*)\);', l)
        if m:
            vd[m.group(1)] = [p.strip() for p in m.group(2).split(',') if p.strip()]
    wd = descs(wj)
    pairs, missing = {}, []
    for l in open(ev, encoding='utf-8'):
        m = re.match(r'(method_\d+) (\w+) (\(.*?\)) -> (.*)$', l.strip())
        if not m:
            continue
        vid, vname, vev, cands = m.group(1), m.group(2), m.group(3), eval(m.group(4))
        if vid in ROLE:
            pairs[vid] = (vname, ROLE[vid][0], 'role: ' + ROLE[vid][1] + ' (ItemBlockRenderTypes.getMovingBlockRenderType returns it where 1.21.10 returned this)')
            continue
        if vid in BY_NAME:
            pairs[vid] = (vname, BY_NAME[vid][0], BY_NAME[vid][1])
            continue
        ok = [c for c in cands if c[1] == vname and wd.get(c[0]) == vd.get(vid)]
        if len(ok) == 1:
            pairs[vid] = (vname, ok[0][0], 'same name, parameters, pipeline and type name ' + str(vev))
        else:
            missing.append((vid, vname, vev, len(ok)))
    lines = []
    for vid in sorted(pairs):
        vname, wid, basis = pairs[vid]
        ps = vd[vid]
        args = ', '.join(f'{p} a{i}' for i, p in enumerate(ps))
        call = ', '.join(f'a{i}' for i in range(len(ps)))
        lines.append(f'    /** 1.21.10 RenderType.{vname}: {basis} */\n'
                     f'    public static class_1921 {vid}({args}) {{\n'
                     f'        return class_12249.{wid}({call});\n    }}\n')
    src = ('package top.dext.centurybridge.step.v1_21_11.rt;\n\n'
           'import net.fabricmc.api.EnvType;\nimport net.fabricmc.api.Environment;\nimport net.minecraft.class_12249;\nimport net.minecraft.class_1921;\n\n'
           '/**\n * 1.21.10\'s RenderType factories, moved by 1.21.11 to rendertype/RenderTypes (generated by\n'
           ' * core/tools/gen_s11_rendertypes.py; each pair\'s bytecode evidence is on the method).\n */\n'
           '@Environment(EnvType.CLIENT)\n'
           'public final class CbRenderTypes {\n    private CbRenderTypes() {\n    }\n\n'
           + '\n'.join(lines) + '}\n')
    open(LAYER, 'w', encoding='utf-8', newline='\n').write(src)
    redirects, moves = {}, {}
    for vid in sorted(pairs):
        d = '(' + ''.join(jtype(p) for p in vd[vid]) + ')Lnet/minecraft/class_1921;'
        redirects[f'net/minecraft/class_1921.{vid}{d}'] = 'top/dext/centurybridge/step/v1_21_11/rt/CbRenderTypes'
        if vid in ROLE:
            continue
        vname, wid, basis = pairs[vid]
        if wd.get(wid) != vd[vid]:
            sys.exit(f'{vid} -> {wid}: parameters differ, not a same-code move')
        moves[f'net/minecraft/class_1921.{vid}{d}'] = {'to': f'net/minecraft/class_12249.{wid}{d}',
                                                       'basis': f'1.21.10 RenderType.{vname} = 1.21.11 RenderTypes.{vname}: {basis}'}
    frag = {
        '_s11_rendertypes_gen_basis': 'generated by core/tools/gen_s11_rendertypes.py: RenderType factories moved to '
                                      'RenderTypes (pairs by bytecode evidence, see CbRenderTypes); BIG/SMALL/TRANSIENT_BUFFER_SIZE '
                                      'renamed in RenderType with the same constants (4194304 / 786432 / 1536)',
        'staticRedirects': redirects,
        'fieldRenames': FIELDS,
        'mixinMoves': moves,
    }
    open(FRAG, 'w', encoding='utf-8', newline='\n').write(json.dumps(frag, indent=1) + '\n')
    print(len(pairs), 'pairs;', len(moves), 'mixinMoves;', len(missing), 'open:')
    for x in missing:
        print('  ', x)


main()
