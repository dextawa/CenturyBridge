"""Write the facades for the Enchantment subclasses 1.20.5 dropped (step 1.20.4 -> 1.20.5, s4item).

Each stands in for its 1.20.4 class (classRenames): a public constructor of the 1.20.4 shape (made with
the category the 1.20.4 constructor passed), and whatever members the class declared beyond the level
range and costs (which rt/CbEnchant's Body table answers for every facade). Read off 1.20.4's bytecode.
usage: python gen_s4item_enchant_facades.py <shim src root>
"""
import os
import sys

PKG = "top.dext.centurybridge.step.v1_20_5.facade"

# name, 1.20.4 intermediary, category constant (None: the constructor takes one), 1.20.5's replacement, extra members
FACADES = [
    ("ArrowFireEnchantment", "class_1877", "field_9070", "flame", ""),
    ("ArrowDamageEnchantment", "class_1878", "field_9070", "power", ""),
    ("ArrowKnockbackEnchantment", "class_1879", "field_9070", "punch", ""),
    ("DiggingEnchantment", "class_1884", "field_9069", "efficiency", ""),
    ("FireAspectEnchantment", "class_1892", "field_9074", "fire aspect", ""),
    ("FishingSpeedEnchantment", "class_1895", None, "lure", ""),
    ("KnockbackEnchantment", "class_1897", "field_9074", "knockback", ""),
    ("OxygenEnchantment", "class_1902", "field_9080", "respiration", ""),
    ("SweepingEdgeEnchantment", "class_1903", "field_9074", "sweeping edge", """
    /** getSweepingDamageRatio(level): 1.20.4's 1 - 1 / (level + 1) */
    public static float method_8241(int level) {
        return 1.0F - 1.0F / (float) (level + 1);
    }
"""),
    ("QuickChargeEnchantment", "class_1904", "field_9081", "quick charge", ""),
    ("TridentChannelingEnchantment", "class_1905", "field_9073", "channeling", ""),
    ("TridentLoyaltyEnchantment", "class_1907", "field_9073", "loyalty", ""),
    ("TridentImpalerEnchantment", "class_1908", "field_9073", "impaling", """
    /** getDamageBonus(level, mobType): 1.20.4's, 2.5 per level against WATER */
    @Override
    public float method_8196(int level, class_1310 mobType) {
        return mobType == class_1310.field_6292 ? (float) level * 2.5F : 0.0F;
    }
"""),
    ("WaterWorkerEnchantment", "class_1912", "field_9080", "aqua affinity", ""),
]


def main():
    out = os.path.join(sys.argv[1], *PKG.split("."))
    for name, inter, cat, now, extra in FACADES:
        if cat is None:
            params = "EnchantmentRarity rarity, EnchantmentCategory category, net.minecraft.class_1304... slots"
            arg = "category"
            made = "the category it is given"
        else:
            params = "EnchantmentRarity rarity, net.minecraft.class_1304... slots"
            arg = "EnchantmentCategory." + cat
            made = "category " + cat
        src = f"""package {PKG};

/**
 * 1.20.4's {name} ({inter}; 1.20.5 builds {now} from a definition and drops the class): the
 * class on 1.20.5's Enchantment, made with {made} as 1.20.4's constructor was. Its level range and
 * costs are its 1.20.4 ones (rt/CbEnchant's Body table). Generated by core/tools/gen_s4item_enchant_facades.py.
 */
public class {name} extends LegacyEnchantment {{

    public {name}({params}) {{
        super({name}.class, rarity, {arg}, slots);
    }}
{extra}}}
"""
        with open(os.path.join(out, name + ".java"), "w", encoding="utf-8", newline="\n") as f:
            f.write(src)
        print("wrote", name)


if __name__ == "__main__":
    main()
