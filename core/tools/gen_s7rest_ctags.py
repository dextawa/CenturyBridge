"""Conventional tags (fabric-convention-tags-v2) that the 1.21.1 Fabric API declares and 1.21.2's does not.

1.21.1's Fabric API (0.116.x) backported conventional tags that 1.21.2's last Fabric API (0.106.1) does not
have. A tag key is its registry and id, so each missing constant is given back as the same TagKey
(TagKey.create(registry, c:<path>), the id read from the 1.21.1 class's static initializer), and its
contents ship with the layer as 1.21.1's Fabric API generated them (data/c/tags/<registry>/<path>.json,
copied verbatim from the 1.21.1 module jar), so the tag holds on 1.21.2 what it held on 1.21.1.

Writes:
  core/segments/steps/1.21.1__1.21.2.json.d/s7rest-ctags-gen.json   fieldGetters
  core/shims/steps/1.21.2/src/top/dext/centurybridge/step/v1_21_2/rt/CbRestConvTags.java
  core/shims/steps/1.21.2/resources/data/c/tags/...                  the tags' 1.21.1 contents

  python3 core/tools/gen_s7rest_ctags.py <1.21.1 fabric-convention-tags-v2 jar> <1.21.2 fabric-convention-tags-v2 jar>
"""
import json
import os
import sys
import zipfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bytecode  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
PKG = 'net/fabricmc/fabric/api/tag/convention/v2/'
# the registry key (Registries.X, intermediary) and the data directory each class's tags live in
REGISTRIES = {
    'ConventionalBiomeTags': ('field_41236', 'worldgen/biome'),
    'ConventionalBlockTags': ('field_41254', 'block'),
    'ConventionalItemTags': ('field_41197', 'item'),
    'ConventionalEntityTypeTags': ('field_41266', 'entity_type'),
    'ConventionalFluidTags': ('field_41270', 'fluid'),
    'ConventionalEnchantmentTags': ('field_41265', 'enchantment'),
    'ConventionalStructureTags': ('field_41246', 'worldgen/structure'),
}


def constants(jar):
    z = zipfile.ZipFile(jar)
    out = {}
    for n in z.namelist():
        if not (n.startswith(PKG) and n.endswith('Tags.class')):
            continue
        k = bytecode.read(z.read(n))
        cl = [m for m in k.methods if m.name == '<clinit>'][0]
        last = None
        for op, a in cl.insns:
            if isinstance(a, tuple) and a[0] == 'str':
                last = a[1]
            if op == 0xb3 and isinstance(a, tuple) and a[4] == 'Lnet/minecraft/class_6862;':
                out[(k.name.split('/')[-1], a[3])] = last
    return out, z


def main():
    old, oz = constants(sys.argv[1])
    new, _ = constants(sys.argv[2])
    gone = sorted(k for k in old if k not in new)
    getters = {}
    lines = []
    copied = 0
    for cls, field in gone:
        reg, folder = REGISTRIES[cls]
        path = old[(cls, field)]
        name = cls[len('Conventional'):-len('Tags')] + '_' + field
        lines.append('    /** %s.%s: c:%s */' % (cls, field, path))
        lines.append('    public static final net.minecraft.class_6862<?> %s = net.minecraft.class_6862.method_40092(net.minecraft.class_7924.%s, '
                     'net.minecraft.class_2960.method_60655("c", "%s"));' % (name, reg, path))
        lines.append('')
        lines.append('    public static net.minecraft.class_6862<?> %s() {' % name)
        lines.append('        return %s;' % name)
        lines.append('    }')
        lines.append('')
        getters['%s%s.%s:Lnet/minecraft/class_6862;' % (PKG, cls, field)] = 'top/dext/centurybridge/step/v1_21_2/rt/CbRestConvTags#' + name
        src = 'data/c/tags/%s/%s.json' % (folder, path)
        dst = os.path.join(ROOT, 'core/shims/steps/1.21.2/resources', src)
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        with open(dst, 'wb') as f:
            f.write(oz.read(src))
        copied += 1
    java = '''package top.dext.centurybridge.step.v1_21_2.rt;

/**
 * Generated by core/tools/gen_s7rest_ctags.py -- do not edit. The conventional tags 1.21.1's Fabric API
 * declares and 1.21.2's does not: the same tag keys (registry and c: id), their 1.21.1 contents shipped in
 * the layer's data/c/tags.
 */
public final class CbRestConvTags {

    private CbRestConvTags() {
    }

''' + '\n'.join(lines).rstrip() + '\n}\n'
    with open(os.path.join(ROOT, 'core/shims/steps/1.21.2/src/top/dext/centurybridge/step/v1_21_2/rt/CbRestConvTags.java'), 'w', encoding='utf-8') as f:
        f.write(java)
    frag = {'_generated': 'core/tools/gen_s7rest_ctags.py -- regenerate, never hand-edit', 'fieldGetters': getters}
    with open(os.path.join(ROOT, 'core/segments/steps/1.21.1__1.21.2.json.d/s7rest-ctags-gen.json'), 'w', encoding='utf-8') as f:
        f.write(json.dumps(frag, indent=1) + '\n')
    print('%d constants given back, %d tag files copied' % (len(gone), copied))


if __name__ == '__main__':
    main()
