"""Land verified bodies as real shim sources and the JSON wiring that reaches them.

Everything here is mechanical on purpose. The model supplied only method
bodies; the surrounding structure is generated from the same rules BridgeForge
used to classify each order, so a body cannot silently end up in a shape the
JVM or Mixin will reject:

  MIXIN_OVERLOAD -> a @Mixin class per target, one overload per body, plus a
                    `covers` entry so the converter stops treating the call as
                    damage (the JVM resolves the old descriptor at runtime)
  STATIC_SHIM    -> a method on Statics, plus a static/instance redirect that
                    rewrites the call site to it
  FIELD_SHIM     -> a zero-arg accessor on Statics, plus a field redirect

A body that throws UnsupportedOperationException still lands: it is a
tombstone with a reason attached, which is what makes the failure legible
instead of a bare NoSuchMethodError. Those also get a ledger line so the
closure check counts them as decided rather than forgotten.
"""
import json
import os
import re
import sys
from collections import defaultdict

# Version-derived at startup (main): the shim tree passed as src_root names
# the target, e.g. core/shims/1.21.1 -> v1_21_1. Nothing here is pinned to a
# corridor anymore.
RT = None
STATICS_PATH = None
VER = None
BEGIN_MARK = "    // ==== GENERATED BRIDGES (assemble.py) ===="
END_MARK = "    // ==== END GENERATED ===="

# Targets that are interfaces in the destination jar: a @Mixin class on one of
# these is fatal at PREPARE. Populated from the stub at startup.
INTERFACES = set()
# method name -> set of descriptors present in the destination stub; used to
# reject guaranteed self-recursive forwards (see below)
STUB_DESCS = {}


def load_stub_descs(stub):
    """Method name -> descriptors in the destination stub, read from the
    StubDump text file (<stub>.dump.txt) when present; produced by the same
    verification tooling the corridor already uses. Absent file = gate off."""
    dump = stub + ".dump.txt"
    if not os.path.exists(dump):
        print(f"  (no {dump}; self-recursion gate inactive)")
        return
    for ln in open(dump, encoding="utf-8"):
        if ln.startswith("M "):
            full = ln[2:].strip()
            owner_name, desc = full.split("(", 1)
            STUB_DESCS.setdefault(owner_name.rsplit(".", 1)[1], set()).add("(" + desc)


def load_interfaces(stub):
    import struct
    import zipfile
    if not stub or not os.path.exists(stub):
        return
    with zipfile.ZipFile(stub) as z:
        for n in z.namelist():
            if not n.endswith(".class") or not n.startswith("net/minecraft/"):
                continue
            data = z.read(n)
            idx, count, i = 10, struct.unpack(">H", data[8:10])[0], 1
            sizes = {7: 3, 8: 3, 16: 3, 19: 3, 20: 3, 15: 4, 9: 5, 10: 5,
                     11: 5, 12: 5, 17: 5, 18: 5, 3: 5, 4: 5, 5: 9, 6: 9}
            while i < count:
                tag = data[idx]
                if tag in (5, 6):
                    idx += 9
                    i += 2
                    continue
                if tag == 1:
                    idx += 3 + struct.unpack(">H", data[idx + 1:idx + 3])[0]
                else:
                    idx += sizes.get(tag, 3)
                i += 1
            if struct.unpack(">H", data[idx:idx + 2])[0] & 0x0200:
                INTERFACES.add(n[:-6])

HEADER = """package top.dext.centurybridge.shims.{ver};

import org.spongepowered.asm.mixin.Mixin;

/**
 * Generated bridge overloads for {target}.
 *
 * Each method re-adds a descriptor this class carried before the corridor
 * boundary and forwards to whatever replaced it. The JVM resolves overloads by
 * descriptor, so an old mod's call site finds the old shape here while new code
 * keeps using the new one.
 *
 * Generated by core/tools/assemble.py -- edit the forge output, not this file.
 */
@Mixin({simple}.class)
public abstract class {cls} {{
"""


def simple_name(owner):
    """net/minecraft/class_1$class_2 -> net.minecraft.class_1.class_2"""
    return "net.minecraft." + owner.split("/")[-1].replace("$", ".")


def class_name(owner):
    return "Gen" + owner.split("/")[-1].replace("$", "_").title().replace("_", "") + "Bridge"


def main():
    global RT, STATICS_PATH, VER
    argv = sys.argv[1:]
    merge = "--merge" in argv
    if merge:
        argv.remove("--merge")
    verified_paths = argv[:-2]
    shims_path = argv[-2]
    src_root = argv[-1]

    # src_root is the generated-bridges package dir:
    # core/shims/<mcver>/src/top/dext/centurybridge/shims/<vX_Y_Z>
    VER = os.path.basename(os.path.normpath(src_root))
    if not re.fullmatch(r"v\d+_\d+(_\d+)?", VER):
        sys.exit(f"src_root must end in the version package (vX_Y_Z), got: {VER}")
    mcver = VER[1:].replace("_", ".")
    RT = f"top/dext/centurybridge/rt/{VER}/Statics"
    STATICS_PATH = os.path.join(os.path.dirname(os.path.dirname(
        os.path.normpath(src_root))), "rt", VER, "Statics.java")
    # a dedicated server loads Statics for every server-side redirect: a body for
    # a client-side owner lands in ClientStatics (@Environment(CLIENT)) instead,
    # so one client type cannot sink the class (build.sh's server-check enforces it)
    client_rt = RT.replace("/Statics", "/ClientStatics")
    client_path = STATICS_PATH.replace("Statics.java", "ClientStatics.java")
    print(f"target {mcver}: RT={RT}")
    print(f"statics: {STATICS_PATH}")

    dest_stub = os.environ.get("CB_DEST_STUB",
                               f"data/jars/client-{mcver}-intermediary.jar")
    load_interfaces(dest_stub)
    load_stub_descs(dest_stub)
    print(f"interface targets known: {len(INTERFACES)}")

    existing = set()   # "owner.name+desc" markers already present in the tree
    if merge and os.path.isdir(src_root):
        import glob as _glob
        probe = _glob.glob(os.path.join(src_root, "*.java"))
        statics_probe = os.path.join(os.path.dirname(os.path.dirname(
            os.path.normpath(src_root))), "rt",
            os.path.basename(os.path.normpath(src_root)), "Statics.java")
        if os.path.exists(statics_probe):
            probe.append(statics_probe)
        for f in probe:
            for m in re.finditer(r"/\*\* was (\S+?) \*/", open(f, encoding="utf-8").read()):
                existing.add(m.group(1))
        # bodies pruned in earlier cycles are known-bad: re-landing them just
        # re-breaks the tree (learned the hard way -- a "dry run" re-landed
        # 150 pruned bodies and the recovery pass ate valid wiring)
        ver = mcver
        for rej in (f"core/out-diff/retry-context-{ver}.json",
                    f"core/out-diff/assemble-rejected-{ver}.json"):
            try:
                for e in json.load(open(rej, encoding="utf-8")):
                    existing.add(e["symbol"])
            except Exception:
                pass
        print(f"merge mode: {len(existing)} bridges already in the tree or known-bad")

    recs = []
    for p in verified_paths:
        if os.path.exists(p):
            recs.extend(json.load(open(p, encoding="utf-8")))
    print(f"landing {len(recs)} verified bodies")

    shims = json.load(open(shims_path, encoding="utf-8"))
    covers = set(shims.setdefault("covers", []))
    sred = shims.setdefault("staticRedirects", {})
    ired = shims.setdefault("instanceRedirects", {})
    fred = shims.setdefault("fieldRedirects", {})
    cred = shims.setdefault("ctorRedirects", {})
    ledger = shims.setdefault("ledger", {})

    by_target = defaultdict(list)
    statics, fields = [], []
    tombstoned = 0

    def rt_of(r):
        return client_rt if r.get("side") == "client" else RT

    OBF_CALL = re.compile(r"\.\s*([a-z]{1,3}\d?)\s*\(")
    SAFE_SHORT = {"get", "put", "add", "map", "of", "abs", "min", "max", "pow",
                  "run", "set", "log", "cos", "sin", "tan", "key", "val", "idx",
                  "len", "pos", "end", "top", "raw"}

    def calls_obf(body):
        """Intermediary names only members with a stable identity; the rest keep
        a short obfuscated name that is different in every release. Such a call
        compiles against whatever stub we hold and then throws NoSuchMethodError
        on the real jar -- and when vanilla itself calls the method we overrode,
        the world dies on the first tick. class_1297.cw() reached a player twice
        before this check existed."""
        for m in OBF_CALL.finditer(body or ""):
            if m.group(1) not in SAFE_SHORT:
                return m.group(1)
        return None

    poisoned = 0
    rejected_recursive = []
    for r in recs:
        owner, name, desc = r["owner"], r["name"], r["oldDesc"]
        if merge and f"{owner}.{name}{desc}" in existing:
            continue   # already landed (and possibly hand-fixed) -- never overwrite
        body = r["body"]
        obf = calls_obf(body)
        if obf:
            poisoned += 1
            continue
        # a body that is nothing but a throw is a tombstone, not a bridge: wired as
        # a cover/redirect it was audited "fixed" while every call threw. Ledger it
        # (the converter tombstones the call site with the same reason) and land
        # nothing.
        if re.fullmatch(r'\s*throw\s+new\s+UnsupportedOperationException\(\s*"(?:[^"\\]|\\.)*"\s*\);\s*(?://[^\n]*\s*)*', body or ""):
            tombstoned += 1
            key = f"{owner}.{name}{desc}" if desc.startswith("(") else f"{owner}.{name}:{desc}"
            if key not in ledger:
                reason = re.search(r'"CenturyBridge: ([^"]+)"', body)
                ledger[key] = ("bridge attempted, no faithful equivalent: "
                               + (reason.group(1) if reason else "see the forge log"))
            continue

        if r["shimKind"] == "MIXIN_OVERLOAD":
            # An anonymous inner class has no source-level name, so it cannot be
            # a @Mixin target -- and it is never API a mod compiled against.
            if re.search(r"\$\d+$", owner):
                continue
            # Self-recursion gate: a forward is guaranteed recursive when every
            # descriptor the stub carries for this name equals the bridge's own
            # -- the merged method overwrites the vanilla one and "forwarding to
            # the new shape" dispatches back to itself (StackOverflowError the
            # moment anything calls it). Found the hard way on class_1297.
            body_selfcalls = re.search(
                r"this\s*\)?\s*\.\s*" + re.escape(name) + r"\(",
                body.replace("(Object) this", "this").replace("(Object)this", "this"))
            descs = STUB_DESCS.get(name)
            if body_selfcalls and descs and all(dd == desc for dd in descs):
                rejected_recursive.append({"symbol": f"{owner}.{name}{desc}",
                                           "reason": "self-recursive forward: descriptor unchanged on target"})
                continue
            # Mixin rejects non-private static methods at APPLY (a whole-game
            # crash); static overloads belong on Statics behind a redirect.
            if r["javaSig"].startswith("public static"):
                statics.append(r)
                sred[f"{owner}.{name}{desc}"] = rt_of(r)
                continue
            # A class mixin on an interface target fails at PREPARE, before any
            # class loads, so the whole game dies rather than one method. Route
            # these to a call-site redirect instead.
            if owner in INTERFACES:
                statics.append(r)
                ired[f"{owner}.{name}{desc}"] = rt_of(r)
                continue
            by_target[owner].append(r)
            covers.add(f"{owner}.{name}{desc}")
        elif r["shimKind"] == "STATIC_SHIM":
            # Statics holds static methods only. A body written against `this`
            # belongs to a mixin and will not compile here -- and a redirect
            # pointing at it would dangle.
            if not r["javaSig"].startswith("public static"):
                continue
            statics.append(r)
            # receiver-as-arg0 shims are reached by an instance redirect; true
            # statics by a static one. java_signature already encoded which.
            if "self" in r["javaSig"]:
                ired[f"{owner}.{name}{desc}"] = rt_of(r)
            else:
                sred[f"{owner}.{name}{desc}"] = rt_of(r)
        elif r["shimKind"] == "FIELD_SHIM":
            fields.append(r)
            fred[f"{owner}.{name}:{desc}"] = rt_of(r)
        elif r["shimKind"] == "CTOR_SHIM":
            if not r["javaSig"].startswith("public static"):
                continue
            m = re.search(r"\s(cbNew\w+)\s*\(", r["javaSig"])
            if not m:
                continue
            statics.append(r)
            # the converter derives nothing from the key here: the factory name
            # travels explicitly (class#member), one per old descriptor
            cred[f"{owner}.<init>{desc}"] = f"{rt_of(r)}#{m.group(1)}"

    # Wipe first: this directory is a build product, and a Gen* file left over
    # from an earlier run is a bridge that is no longer verified -- it will
    # still be copied into the shim tree and break the build. In merge mode the
    # tree is a hand-curated survivor set instead: never delete, only add.
    if not merge and os.path.isdir(src_root):
        for f in os.listdir(src_root):
            if f.startswith("Gen") or f.startswith("Statics.generated"):
                os.remove(os.path.join(src_root, f))
    os.makedirs(src_root, exist_ok=True)
    written = 0
    for owner, group in sorted(by_target.items()):
        cls = class_name(owner)
        out = [HEADER.format(ver=VER, target=owner, simple=simple_name(owner), cls=cls)]
        seen = set()
        for r in sorted(group, key=lambda x: x["name"] + x["oldDesc"]):
            sig = r["javaSig"]
            if sig in seen:
                continue  # same descriptor reached from both boundaries
            seen.add(sig)
            out.append(f"    /** was {r['owner']}.{r['name']}{r['oldDesc']} */")
            # Bodies that delegate to IO-ish game methods inherit their checked
            # exceptions; the probe compiles each method alone and does not
            # always surface that, so declare them rather than lose the bridge.
            throws = (" throws Exception"
                      if "Exception" not in sig and any(
                          k in r["body"] for k in ("method_10633", "method_10630",
                                                   "method_30614", "method_10629",
                                                   "Files.", "InputStream", "OutputStream"))
                      else "")
            out.append(f"    {sig}{throws} {{")
            out.extend("        " + line for line in r["body"].splitlines())
            out.append("    }\n")
        out.append("}\n")
        with open(os.path.join(src_root, cls + ".java"), "w", encoding="utf-8",
                  newline="\n") as f:
            f.write("\n".join(out))
        written += 1

    # Generated Statics methods are spliced straight into Statics.java. They
    # used to land in a .part file "for review", which meant 259 redirect
    # targets existed only in the JSON: the wiring compiled, and the game threw
    # NoSuchMethodError the moment a mod reached one of them.
    def splice(path, recs, cls):
        if not recs:
            return 0
        gen, seen_sigs = [], set()
        for r in sorted(recs, key=lambda x: x["owner"] + x["name"]):
            sig = r["javaSig"]
            if sig in seen_sigs:
                continue                    # same shape reached from two boundaries
            seen_sigs.add(sig)
            gen.append(f"    /** was {r['owner']}.{r['name']}{r['oldDesc']} */")
            gen.append(f"    {sig} {{")
            gen.extend("        " + line for line in r["body"].splitlines())
            gen.append("    }\n")

        if not os.path.exists(path):
            open(path, "w", encoding="utf-8", newline="\n").write(
                f"package top.dext.centurybridge.rt.{VER};\n\n"
                "/** The client half of Statics: redirect targets whose bodies name client-only classes. */\n"
                "@net.fabricmc.api.Environment(net.fabricmc.api.EnvType.CLIENT)\n"
                f"public final class {cls} {{\n\n    private {cls}() {{\n    }}\n}}\n")
        src = open(path, encoding="utf-8").read()
        block = (BEGIN_MARK + "\n" + "\n".join(gen) + "\n" + END_MARK + "\n")
        if merge and END_MARK in src:
            # merge mode APPENDS inside the existing block; the full-replace
            # below would throw away every previously landed method (which is
            # exactly what happened when this branch went missing)
            src = src.replace(END_MARK, "\n".join(gen) + "\n" + END_MARK, 1)
        elif BEGIN_MARK in src:
            head = src[:src.index(BEGIN_MARK)]
            tail = src[src.index(END_MARK) + len(END_MARK):].lstrip("\n")
            src = head + block + tail
        else:
            anchor = f"    private {cls}() {{"
            src = src.replace(anchor, block + "\n" + anchor, 1)
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(src)
        print(f"  spliced {len(seen_sigs)} generated methods into {cls}.java")
        return len(seen_sigs)

    server_recs = [r for r in statics + fields if rt_of(r) == RT]
    client_recs = [r for r in statics + fields if rt_of(r) != RT]
    splice(STATICS_PATH, server_recs, "Statics")
    splice(client_path, client_recs, "ClientStatics")

    shims["covers"] = sorted(covers)
    with open(shims_path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(shims, f, indent=1, ensure_ascii=False)

    if poisoned:
        print(f"  rejected {poisoned} bodies calling obfuscated names")
    if rejected_recursive:
        rr = shims_path.replace("shims-", "assemble-rejected-").replace(
            "core/segments", "core/out-diff").replace("core\\segments", "core/out-diff")
        try:
            prev = json.load(open(rr, encoding="utf-8"))
        except Exception:
            prev = []
        with open(rr, "w", encoding="utf-8", newline=chr(10)) as f:
            json.dump(prev + rejected_recursive, f, indent=1)
        print(f"  rejected {len(rejected_recursive)} self-recursive forwards -> {rr}")
    print(f"  mixin classes:   {written} ({sum(len(v) for v in by_target.values())} overloads)")
    print(f"  Statics methods: {len(statics)} + {len(fields)} field accessors")
    print(f"  tombstones:      {tombstoned} (each with a stated reason)")
    print(f"  covers={len(covers)} static={len(sred)} instance={len(ired)} field={len(fred)}")


if __name__ == "__main__":
    main()
